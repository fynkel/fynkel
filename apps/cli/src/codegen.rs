//! Native schema generator (ADR-0012 pipeline (a)):
//! Rust `RecordSchema` registry → JSON Schema, Dart codecs, Rust codecs.
//! Deterministic output; `--check` diffs against the committed files.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use fynkel_contracts::schema::{EnumSchema, FieldType, RecordSchema, SchemaKind};
use fynkel_contracts::ABI_VERSION;
use fynkel_core::schema::{schema_fingerprint, ALL};
use serde_json::{json, Value};

pub enum Outcome {
    Written(usize),
    UpToDate,
    Drift(Vec<PathBuf>),
}

pub const DART_OUT: &str = "packages/fynkel/lib/generated/schema.g.dart";
pub const RUST_OUT: &str = "crates/fynkel_wire/src/generated.rs";
pub const DOCUMENT_OUT: &str = "crates/fynkel_document/src/generated.rs";
pub const JSON_INDEX: &str = "schemas/fynkel.schema.json";
pub const SCENE_SCHEMA: &str = "schemas/scene.schema.json";
pub const PREFAB_SCHEMA: &str = "schemas/prefab.schema.json";
/// Document schemas maintained by hand under `schemas/` (no Rust source of
/// truth) that `fynkel_document` still embeds; the envelope is embedded by
/// `SchemaSet` itself.
pub const HAND_WRITTEN_SCHEMAS: &[&str] = &["material.schema.json", "shader.schema.json"];
pub const ENVELOPE_ID: &str = "https://fynkel.dev/schemas/envelope.schema.json";

pub fn run(root: &Path, check: bool) -> Result<Outcome, String> {
    let files = generate();
    if check {
        let mut drift = Vec::new();
        for (rel, content) in &files {
            let path = root.join(rel);
            if std::fs::read_to_string(&path).ok().as_deref() != Some(content.as_str()) {
                drift.push(PathBuf::from(rel));
            }
        }
        return Ok(if drift.is_empty() {
            Outcome::UpToDate
        } else {
            Outcome::Drift(drift)
        });
    }
    for (rel, content) in &files {
        let path = root.join(rel);
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
        }
        std::fs::write(&path, content).map_err(|e| format!("{}: {e}", path.display()))?;
    }
    Ok(Outcome::Written(files.len()))
}

/// All outputs as (repo-relative path, content), deterministic order.
pub fn generate() -> Vec<(String, String)> {
    let fp = schema_fingerprint();
    let mut out = vec![
        (JSON_INDEX.to_string(), json_index(fp)),
        (
            SCENE_SCHEMA.to_string(),
            pretty(&entity_document_schema(EntityDocument::Scene)),
        ),
        (
            PREFAB_SCHEMA.to_string(),
            pretty(&entity_document_schema(EntityDocument::Prefab)),
        ),
        (DART_OUT.to_string(), dart(fp)),
        (RUST_OUT.to_string(), rust(fp)),
        (DOCUMENT_OUT.to_string(), document_codecs(fp)),
    ];
    for s in ALL.iter().filter(|s| s.kind == SchemaKind::Component) {
        out.push((
            format!("schemas/components/{}.schema.json", s.name),
            pretty(&json_schema(s)),
        ));
    }
    out
}

fn pretty(v: &Value) -> String {
    let mut s = serde_json::to_string_pretty(v).unwrap();
    s.push('\n');
    s
}

fn rust_ident(s: &RecordSchema) -> &str {
    s.rust_path.rsplit("::").next().unwrap()
}

// ------------------------------------------------------------------ JSON

fn json_index(fp: u64) -> String {
    let records: Vec<Value> = ALL
        .iter()
        .map(|s| {
            let offsets = s.offsets();
            json!({
                "kind": s.kind.name(),
                "id": s.id,
                "name": s.name,
                "rust": s.rust_path,
                "doc": s.doc,
                "size": s.wire_size(),
                "fields": s.fields.iter().zip(offsets).map(|(f, off)| {
                    let mut v = json!({
                        "name": f.name,
                        "type": f.ty.name(),
                        "offset": off,
                        "size": f.ty.wire_size(),
                        "doc": f.doc,
                    });
                    if let FieldType::Enum(e) = f.ty {
                        v["variants"] = json!(e.variants);
                    }
                    v
                }).collect::<Vec<_>>(),
            })
        })
        .collect();
    pretty(&json!({
        "$comment": "GENERATED by `fynkel codegen` from the Rust schemas (ADR-0012). Do not edit.",
        "abiVersion": ABI_VERSION,
        "schemaFingerprint": format!("{fp:#018x}"),
        "layout": "little-endian; fields at natural alignment in declaration order; records padded to 8; str = (offset u32, len u32) into the buffer string tail",
        "records": records,
    }))
}

fn json_type(ty: &FieldType) -> Value {
    match ty {
        FieldType::F32 => json!({"type": "number"}),
        FieldType::U32 => json!({"type": "integer", "minimum": 0, "maximum": u32::MAX}),
        FieldType::I32 => json!({"type": "integer", "minimum": i32::MIN, "maximum": i32::MAX}),
        FieldType::U64 | FieldType::Entity => json!({"type": "integer", "minimum": 0}),
        FieldType::OptionalEntity => json!({"type": ["integer", "null"], "minimum": 0}),
        FieldType::Bool => json!({"type": "boolean"}),
        FieldType::Vec3 => {
            json!({"type": "array", "items": {"type": "number"}, "minItems": 3, "maxItems": 3})
        }
        FieldType::Quat => {
            json!({"type": "array", "items": {"type": "number"}, "minItems": 4, "maxItems": 4, "description": "[x, y, z, w]"})
        }
        FieldType::Str => json!({"type": "string"}),
        FieldType::Nested(s) => json!({"$ref": format!("{}.schema.json", s.name)}),
        FieldType::AssetRef => json!({"$ref": format!("{ENVELOPE_ID}#/$defs/assetRef")}),
        FieldType::Enum(e) => {
            json!({"type": "string", "enum": e.variants, "x-fynkel": {"enum": e.name}})
        }
    }
}

fn json_schema(s: &RecordSchema) -> Value {
    let mut props = serde_json::Map::new();
    let mut required = Vec::new();
    for f in s.fields {
        let mut t = json_type(&f.ty);
        if !f.doc.is_empty() {
            t["description"] = Value::String(f.doc.to_string());
        }
        props.insert(f.name.to_string(), t);
        if !matches!(f.ty, FieldType::OptionalEntity) {
            required.push(f.name);
        }
    }
    json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": format!("https://fynkel.dev/schemas/components/{}.schema.json", s.name),
        "$comment": "GENERATED by `fynkel codegen`. Do not edit.",
        "title": s.name,
        "description": s.doc,
        "type": "object",
        "properties": props,
        "required": required,
        "additionalProperties": false,
        "x-fynkel": {"kind": s.kind.name(), "id": s.id, "rust": s.rust_path, "wireSize": s.wire_size(), "authored": s.authored},
    })
}

fn component_schema_id(name: &str) -> String {
    format!("https://fynkel.dev/schemas/components/{name}.schema.json")
}

/// `scene.schema.json` (blueprint §6, §19.2c item 3): the document model
/// plus, for every authored built-in component, a conditional that binds
/// `data` to that component's schema. Unknown component types validate
/// structurally (`data` is any object) and are reported by the semantic
/// pass, so a project with a missing plugin still opens.
#[derive(Clone, Copy, PartialEq, Eq)]
enum EntityDocument {
    Scene,
    Prefab,
}

/// `scene.schema.json` and `prefab.schema.json` share the entity/component
/// model; a scene entity may be a prefab instance (`prefab`), a prefab
/// declares its `roots` and may not contain instances (nested prefabs are
/// out of M2 scope).
fn entity_document_schema(kind: EntityDocument) -> Value {
    let uuid = json!({"$ref": format!("{ENVELOPE_ID}#/$defs/uuid")});
    let asset_ref = json!({"$ref": format!("{ENVELOPE_ID}#/$defs/assetRef")});
    let type_id = json!({"$ref": format!("{ENVELOPE_ID}#/$defs/typeId")});
    let bindings: Vec<Value> = ALL
        .iter()
        .filter(|s| s.kind == SchemaKind::Component && s.authored)
        .map(|s| {
            json!({
                "if": {"properties": {"type": {"const": s.name}}},
                "then": {"properties": {"data": {"$ref": component_schema_id(s.name)}}},
            })
        })
        .collect();
    let mut entity_properties = json!({
        "name": {"type": "string", "maxLength": 256},
        "parent": {"oneOf": [uuid, {"type": "null"}]},
        "children": {
            "type": "array",
            "description": "Ordered child ids; every listed child must name this entity as its parent.",
            "items": uuid,
        },
        "components": {
            "type": "object",
            "propertyNames": uuid,
            "additionalProperties": {"$ref": "#/$defs/component"},
        },
        "editorNotes": {"type": "string"},
    });
    let mut properties = json!({
        "entities": {
            "type": "object",
            "description": "Entity records keyed by their persistent id. Roots are the entities with a null parent, in key order.",
            "propertyNames": uuid,
            "additionalProperties": {"$ref": "#/$defs/entity"},
        },
    });
    let mut defs = json!({
        "component": {
            "type": "object",
            "properties": {
                "type": type_id,
                "version": {"type": "integer", "minimum": 1},
                "data": {"type": "object"},
                "editorNotes": {"type": "string"},
            },
            "required": ["type", "version", "data"],
            "patternProperties": {"^x-": true},
            "additionalProperties": false,
            "allOf": bindings,
        },
    });
    let (id, title, description, required) = match kind {
        EntityDocument::Scene => {
            entity_properties["prefab"] = json!({"$ref": "#/$defs/prefabInstance"});
            defs["prefabInstance"] = json!({
                "type": "object",
                "description": "Makes this entity a prefab instance: the prefab's roots are expanded as its children (after the authored ones), with prefab-local ids remapped per instance. Overrides apply in order.",
                "properties": {
                    "asset": asset_ref,
                    "instance": {"allOf": [uuid], "description": "Stable per instance; prefab-local ids are derived from it."},
                    "overrides": {"type": "array", "items": {"$ref": "#/$defs/override"}},
                },
                "required": ["asset", "instance"],
                "patternProperties": {"^x-": true},
                "additionalProperties": false,
            });
            defs["override"] = json!({
                "type": "object",
                "description": "One explicit operation on the instance, addressed by prefab-local ids (or ids introduced by an earlier addObject/addComponent). `setField` with a null value sets null; `unsetField` removes the field.",
                "properties": {
                    "op": {"enum": ["setField", "unsetField", "addComponent", "removeComponent", "addObject", "removeObject"]},
                    "entity": uuid,
                    "component": uuid,
                    "field": {"type": "string", "minLength": 1},
                    "value": {},
                    "type": type_id,
                    "version": {"type": "integer", "minimum": 1},
                    "data": {"type": "object"},
                    "name": {"type": "string", "maxLength": 256},
                    "parent": {"oneOf": [uuid, {"type": "null"}], "description": "addObject: prefab-local parent, or null for a new instance root."},
                    "components": {
                        "type": "object",
                        "propertyNames": uuid,
                        "additionalProperties": {"$ref": "#/$defs/component"},
                    },
                },
                "required": ["op", "entity"],
                "allOf": [
                    {"if": {"properties": {"op": {"const": "setField"}}}, "then": {"required": ["component", "field", "value"]}},
                    {"if": {"properties": {"op": {"const": "unsetField"}}}, "then": {"required": ["component", "field"]}},
                    {"if": {"properties": {"op": {"const": "addComponent"}}}, "then": {"required": ["component", "type", "version", "data"]}},
                    {"if": {"properties": {"op": {"const": "removeComponent"}}}, "then": {"required": ["component"]}},
                    {"if": {"properties": {"op": {"const": "addObject"}}}, "then": {"required": ["name", "parent"]}},
                ],
                "patternProperties": {"^x-": true},
                "additionalProperties": false,
            });
            (
                "scene",
                "Fynkel scene document",
                "UUID-keyed entities and component instances; child order is stored per entity (blueprint §6). An entity with `prefab` is a prefab instance. Semantic rules (dangling references, cycles, duplicate component types, prefab resolution and override targets) are checked by `fynkel scene validate`, not by this schema.",
                json!(["entities"]),
            )
        }
        EntityDocument::Prefab => {
            properties["roots"] = json!({
                "type": "array",
                "description": "The parentless entities, in instantiation order; must list each exactly once.",
                "items": uuid,
                "uniqueItems": true,
            });
            (
                "prefab",
                "Fynkel prefab document",
                "The scene entity model plus declared `roots` (blueprint §6 Prefabs). A prefab may not contain prefab instances (nested prefabs are post-M2). `fynkel prefab validate` checks the semantic rules.",
                json!(["entities", "roots"]),
            )
        }
    };
    defs["entity"] = json!({
        "type": "object",
        "properties": entity_properties,
        "required": ["name", "parent", "children", "components"],
        "patternProperties": {"^x-": true},
        "additionalProperties": false,
    });
    json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": format!("https://fynkel.dev/schemas/{id}.schema.json"),
        "$comment": "GENERATED by `fynkel codegen` from the document model and the Rust component schemas (ADR-0012). Do not edit.",
        "title": title,
        "description": description,
        "type": "object",
        "allOf": [{"$ref": ENVELOPE_ID}],
        "properties": properties,
        "required": required,
        "patternProperties": {"^x-": true},
        "unevaluatedProperties": false,
        "$defs": defs,
    })
}

// ------------------------------------------------------------------ Dart

fn camel(s: &str) -> String {
    let mut out = String::new();
    let mut up = false;
    for c in s.chars() {
        if c == '_' {
            up = true;
        } else if up {
            out.push(c.to_ascii_uppercase());
            up = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn dart_type(ty: &FieldType) -> String {
    match ty {
        FieldType::F32 => "double".into(),
        FieldType::U32 | FieldType::I32 | FieldType::U64 | FieldType::Entity => "int".into(),
        FieldType::OptionalEntity => "int?".into(),
        FieldType::Bool => "bool".into(),
        FieldType::Vec3 => "Vec3".into(),
        FieldType::Quat => "Quat".into(),
        FieldType::Str => "String".into(),
        FieldType::Nested(s) => rust_ident(s).into(),
        FieldType::AssetRef => "AssetRef".into(),
        FieldType::Enum(e) => enum_ident(e).into(),
    }
}

fn enum_ident(e: &EnumSchema) -> &str {
    e.rust_path.rsplit("::").next().unwrap()
}

/// Every enum used by a field in `ALL`, first-use order, once each.
fn enums() -> Vec<&'static EnumSchema> {
    let mut out: Vec<&'static EnumSchema> = Vec::new();
    for s in ALL {
        for f in s.fields {
            if let FieldType::Enum(e) = f.ty {
                if !out.iter().any(|x| x.name == e.name) {
                    out.push(e);
                }
            }
        }
    }
    out
}

fn dart(fp: u64) -> String {
    let mut o = String::new();
    let _ = writeln!(
        o,
        "// GENERATED by `fynkel codegen` from the Rust component schemas (ADR-0012)."
    );
    let _ = writeln!(o, "// Do not edit. Schema fingerprint {fp:#018x}.");
    let _ = writeln!(o, "//");
    let _ = writeln!(
        o,
        "// ignore_for_file: unused_import, prefer_const_constructors"
    );
    let _ = writeln!(o);
    let _ = writeln!(o, "import 'dart:typed_data';");
    let _ = writeln!(o);
    let _ = writeln!(o, "import '../math.dart';");
    let _ = writeln!(o, "import '../src/asset_ref.dart';");
    let _ = writeln!(o, "import '../src/wire/support.dart';");
    let _ = writeln!(o);
    let _ = writeln!(
        o,
        "/// Fingerprint of the schemas these codecs implement; must equal the"
    );
    let _ = writeln!(o, "/// native library's `fynkel_schema_fingerprint()`.");
    let _ = writeln!(o, "const int schemaFingerprint = {fp:#x};");
    let _ = writeln!(o, "const int abiVersion = {ABI_VERSION};");
    for e in enums() {
        let _ = writeln!(o);
        if !e.doc.is_empty() {
            let _ = writeln!(o, "/// {}", e.doc);
            let _ = writeln!(o, "///");
        }
        let _ = writeln!(
            o,
            "/// `{}`: the wire carries the index, documents the name.",
            e.name
        );
        let _ = writeln!(o, "enum {} {{", enum_ident(e));
        for v in e.variants {
            let _ = writeln!(o, "  {v},");
        }
        let _ = writeln!(o, "}}");
    }
    for s in ALL {
        let name = rust_ident(s);
        let offsets = s.offsets();
        let _ = writeln!(o);
        if !s.doc.is_empty() {
            let _ = writeln!(o, "/// {}", s.doc);
            let _ = writeln!(o, "///");
        }
        let _ = writeln!(
            o,
            "/// `{}` ({}, id {}, {} bytes).",
            s.name,
            s.kind.name(),
            s.id,
            s.wire_size()
        );
        let _ = writeln!(o, "class {name} implements WireRecord {{");
        // constructor
        if s.fields.is_empty() {
            let _ = writeln!(o, "  const {name}();");
        } else {
            let _ = writeln!(o, "  const {name}({{");
            for f in s.fields {
                let req = if matches!(f.ty, FieldType::OptionalEntity) {
                    ""
                } else {
                    "required "
                };
                let _ = writeln!(o, "    {req}this.{},", camel(f.name));
            }
            let _ = writeln!(o, "  }});");
        }
        let _ = writeln!(o);
        for f in s.fields {
            if !f.doc.is_empty() {
                let _ = writeln!(o, "  /// {}", f.doc);
            }
            let _ = writeln!(o, "  final {} {};", dart_type(&f.ty), camel(f.name));
        }
        let _ = writeln!(o);
        let _ = writeln!(o, "  static const String schemaName = '{}';", s.name);
        let _ = writeln!(o, "  static const int wireSize = {};", s.wire_size());
        match s.kind {
            SchemaKind::Component => {
                let _ = writeln!(o, "  static const int componentId = {};", s.id);
            }
            SchemaKind::Command => {
                let _ = writeln!(o, "  static const int commandKind = {};", s.id);
            }
            SchemaKind::Event => {
                let _ = writeln!(o, "  static const int eventKind = {};", s.id);
            }
            SchemaKind::Record => {}
        }
        // encode
        let _ = writeln!(o);
        let _ = writeln!(
            o,
            "  /// Writes [wireSize] bytes at [offset]; strings go to [strings]."
        );
        let _ = writeln!(
            o,
            "  @override\n  void encode(ByteData d, int offset, WireStrings strings) {{"
        );
        for (f, off) in s.fields.iter().zip(&offsets) {
            let v = camel(f.name);
            let line = match f.ty {
                FieldType::F32 => format!("d.setFloat32(offset + {off}, {v}, Endian.little);"),
                FieldType::U32 => format!("d.setUint32(offset + {off}, {v}, Endian.little);"),
                FieldType::I32 => format!("d.setInt32(offset + {off}, {v}, Endian.little);"),
                FieldType::U64 | FieldType::Entity => {
                    format!("d.setUint64(offset + {off}, {v}, Endian.little);")
                }
                FieldType::OptionalEntity => {
                    format!("d.setUint64(offset + {off}, {v} ?? 0, Endian.little);")
                }
                FieldType::Bool => format!("d.setUint8(offset + {off}, {v} ? 1 : 0);"),
                FieldType::Vec3 => format!("writeVec3(d, offset + {off}, {v});"),
                FieldType::Quat => format!("writeQuat(d, offset + {off}, {v});"),
                FieldType::Str => format!("writeWireString(d, offset + {off}, {v}, strings);"),
                FieldType::Nested(_) => format!("{v}.encode(d, offset + {off}, strings);"),
                FieldType::AssetRef => format!("writeAssetRef(d, offset + {off}, {v}, strings);"),
                FieldType::Enum(_) => {
                    format!("d.setUint32(offset + {off}, {v}.index, Endian.little);")
                }
            };
            let _ = writeln!(o, "    {line}");
        }
        let _ = writeln!(o, "  }}");
        // decode
        let _ = writeln!(o);
        let _ = writeln!(
            o,
            "  /// Reads [wireSize] bytes at [offset]; [tail] resolves strings."
        );
        let _ = writeln!(
            o,
            "  static {name} decode(ByteData d, int offset, Uint8List tail) {{"
        );
        if s.fields.is_empty() {
            let _ = writeln!(o, "    return const {name}();");
        } else {
            let _ = writeln!(o, "    return {name}(");
            for (f, off) in s.fields.iter().zip(&offsets) {
                let v = camel(f.name);
                let expr = match f.ty {
                    FieldType::F32 => format!("d.getFloat32(offset + {off}, Endian.little)"),
                    FieldType::U32 => format!("d.getUint32(offset + {off}, Endian.little)"),
                    FieldType::I32 => format!("d.getInt32(offset + {off}, Endian.little)"),
                    FieldType::U64 | FieldType::Entity => {
                        format!("d.getUint64(offset + {off}, Endian.little)")
                    }
                    FieldType::OptionalEntity => {
                        format!("optionalEntity(d.getUint64(offset + {off}, Endian.little))")
                    }
                    FieldType::Bool => format!("d.getUint8(offset + {off}) != 0"),
                    FieldType::Vec3 => format!("readVec3(d, offset + {off})"),
                    FieldType::Quat => format!("readQuat(d, offset + {off})"),
                    FieldType::Str => format!("readWireString(d, offset + {off}, tail)"),
                    FieldType::Nested(n) => {
                        format!("{}.decode(d, offset + {off}, tail)", rust_ident(n))
                    }
                    FieldType::AssetRef => format!("readAssetRef(d, offset + {off}, tail)"),
                    FieldType::Enum(e) => format!(
                        "enumValue({}.values, d.getUint32(offset + {off}, Endian.little), '{}')",
                        enum_ident(e),
                        e.name
                    ),
                };
                let _ = writeln!(o, "      {v}: {expr},");
            }
            let _ = writeln!(o, "    );");
        }
        let _ = writeln!(o, "  }}");
        // equality + toString
        let _ = writeln!(o);
        let _ = writeln!(o, "  @override");
        let _ = writeln!(o, "  bool operator ==(Object other) =>");
        let _ = write!(o, "      other is {name}");
        for f in s.fields {
            let v = camel(f.name);
            let _ = write!(o, " && other.{v} == {v}");
        }
        let _ = writeln!(o, ";");
        let _ = writeln!(o);
        let _ = writeln!(o, "  @override");
        if s.fields.is_empty() {
            let _ = writeln!(o, "  int get hashCode => schemaName.hashCode;");
        } else {
            let _ = writeln!(
                o,
                "  int get hashCode => Object.hashAll([{}]);",
                s.fields
                    .iter()
                    .map(|f| camel(f.name))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
        }
        let _ = writeln!(o);
        let _ = writeln!(o, "  @override");
        let _ = write!(o, "  String toString() => '{name}(");
        let parts: Vec<String> = s
            .fields
            .iter()
            .map(|f| {
                let v = camel(f.name);
                format!("{v}: ${v}")
            })
            .collect();
        let _ = write!(o, "{}", parts.join(", "));
        let _ = writeln!(o, ")';");
        let _ = writeln!(o, "}}");
    }
    o
}

