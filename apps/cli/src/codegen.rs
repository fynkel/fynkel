fn rust(fp: u64) -> String {
    let mut o = String::new();
    let _ = writeln!(
        o,
        "// GENERATED by `fynkel codegen` from the Rust component schemas (ADR-0012)."
    );
    let _ = writeln!(o, "// Do not edit. Schema fingerprint {fp:#018x}.");
    let _ = writeln!(o);
    let _ = writeln!(o, "use crate::*;");
    let _ = writeln!(o);
    let _ = writeln!(
        o,
        "/// Derived from `fynkel_core::schema::ALL`; `fynkel codegen --check` guards drift."
    );
    let _ = writeln!(o, "pub const SCHEMA_FINGERPRINT: u64 = {fp:#018x};");
    for s in ALL {
        let path = format!("::{}", s.rust_path);
        let offsets = s.offsets();
        let _ = writeln!(o);
        let _ = writeln!(o, "/// `{}` ({}, id {}).", s.name, s.kind.name(), s.id);
        let _ = writeln!(o, "impl WireRecord for {path} {{");
        let _ = writeln!(o, "    const SIZE: usize = {};", s.wire_size());
        let _ = writeln!(
            o,
            "    fn encode(&self, out: &mut [u8], strings: &mut StringTable) {{"
        );
        let _ = writeln!(o, "        let out = &mut out[..Self::SIZE];");
        let _ = writeln!(o, "        let _ = (&out, &strings);");
        for (f, off) in s.fields.iter().zip(&offsets) {
            let v = format!("self.{}", f.name);
            let line = match f.ty {
                FieldType::F32 => format!("put_f32(out, {off}, {v});"),
                FieldType::U32 => format!("put_u32(out, {off}, {v});"),
                FieldType::I32 => format!("put_i32(out, {off}, {v});"),
                FieldType::U64 => format!("put_u64(out, {off}, {v});"),
                FieldType::Entity => format!("put_entity(out, {off}, {v});"),
                FieldType::OptionalEntity => format!("put_opt_entity(out, {off}, {v});"),
                FieldType::Bool => format!("put_bool(out, {off}, {v});"),
                FieldType::Vec3 => format!("put_vec3(out, {off}, {v});"),
                FieldType::Quat => format!("put_quat(out, {off}, {v});"),
                FieldType::Str => format!("put_str(out, {off}, &{v}, strings);"),
                FieldType::Nested(n) => format!(
                    "<::{} as WireRecord>::encode(&{v}, &mut out[{off}..{}], strings);",
                    n.rust_path,
                    off + n.wire_size()
                ),
                FieldType::AssetRef => format!("put_asset_ref(out, {off}, &{v}, strings);"),
                FieldType::Enum(_) => format!("put_enum(out, {off}, &{v});"),
            };
            let _ = writeln!(o, "        {line}");
        }
        let _ = writeln!(o, "    }}");
        let _ = writeln!(
            o,
            "    fn decode(b: &[u8], tail: &[u8]) -> Result<Self, WireError> {{"
        );
        let _ = writeln!(o, "        check_len(b, Self::SIZE)?;");
        let _ = writeln!(o, "        let _ = tail;");
        if s.fields.is_empty() {
            let _ = writeln!(o, "        Ok(Self)");
        } else {
            let _ = writeln!(o, "        Ok(Self {{");
            for (f, off) in s.fields.iter().zip(&offsets) {
                let expr = match f.ty {
                    FieldType::F32 => format!("get_f32(b, {off})"),
                    FieldType::U32 => format!("get_u32(b, {off})"),
                    FieldType::I32 => format!("get_i32(b, {off})"),
                    FieldType::U64 => format!("get_u64(b, {off})"),
                    FieldType::Entity => format!("get_entity(b, {off})"),
                    FieldType::OptionalEntity => format!("get_opt_entity(b, {off})"),
                    FieldType::Bool => format!("get_bool(b, {off})"),
                    FieldType::Vec3 => format!("get_vec3(b, {off})"),
                    FieldType::Quat => format!("get_quat(b, {off})"),
                    FieldType::Str => format!("get_str(b, {off}, tail)?"),
                    FieldType::Nested(n) => format!(
                        "<::{} as WireRecord>::decode(&b[{off}..{}], tail)?",
                        n.rust_path,
                        off + n.wire_size()
                    ),
                    FieldType::AssetRef => format!("get_asset_ref(b, {off}, tail)?"),
                    FieldType::Enum(_) => format!("get_enum(b, {off})?"),
                };
                let _ = writeln!(o, "            {}: {expr},", f.name);
            }
            let _ = writeln!(o, "        }})");
        }
        let _ = writeln!(o, "    }}");
        let _ = writeln!(o, "}}");
    }
    o
}

