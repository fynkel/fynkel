//! JSON Schema 2020-12 validation (§6) over the schemas in a `schemas/`
//! directory: the engine's own checkout or a project's copy. Every
//! `*.schema.json` under the directory is registered by its `$id` so
//! `$ref`s between them resolve locally; nothing is fetched.

use std::collections::HashMap;
use std::path::{Path, PathBuf};

use fynkel_contracts::{Code, Diagnostic, Severity};
use jsonschema::{Draft, Registry, Resource, ValidationError, Validator};

use crate::json::{Locator, Node};
use crate::DocumentKind;

/// The shared envelope schema, embedded so validation works before any
/// `schemas/` directory exists (and as the fallback for kinds without a
/// generated schema yet).
pub const ENVELOPE_SCHEMA: &str = include_str!("../../../schemas/envelope.schema.json");

pub struct SchemaSet {
    validators: HashMap<DocumentKind, Validator>,
    envelope: Validator,
    /// Kinds that fell back to the envelope schema.
    missing: Vec<DocumentKind>,
    /// Built-in component schemas by type id (`schemas/components/*`), the
    /// committed codegen metadata ADR-0016 says tools read.
    components: HashMap<String, ComponentInfo>,
    /// Behaviour types by type id: schemas with `x-fynkel.kind ==
    /// "behaviour"` (`schemas/behaviours/<id>.schema.json`, generated by
    /// `fynkel codegen` from `@FynkelBehaviour` classes) plus the types a
    /// project registry declares without a schema ([`declare_behaviour`]).
    ///
    /// [`declare_behaviour`]: SchemaSet::declare_behaviour
    behaviours: HashMap<String, BehaviourInfo>,
    /// Data asset types by type id (ADR-0027): schemas with
    /// `x-fynkel.kind == "data"` (`schemas/data/<id>.schema.json`) plus the
    /// types a project registry declares (kind `data`).
    data_types: HashMap<String, BehaviourInfo>,
    /// Every other loaded schema by `$id` (`lock.schema.json`, …).
    others: HashMap<String, Validator>,
    /// What this set was built from, so [`extended_with`] can rebuild it
    /// with more files.
    ///
    /// [`extended_with`]: SchemaSet::extended_with
    sources: Vec<(PathBuf, serde_json::Value)>,
    /// Declarations replayed by [`extended_with`](SchemaSet::extended_with).
    declared: Vec<(String, u32)>,
    declared_data: Vec<(String, u32)>,
    /// The fields of each component and behaviour type that name assets
    /// of a kind (`FYN-A0007`, [`crate::reference_kinds`]).
    asset_fields: HashMap<String, Vec<crate::reference_kinds::AssetField>>,
}

/// A known behaviour type: a Dart class instantiated by the SDK, never by
/// the runtime. Its `data` is validated here when a schema was loaded;
/// a declared-only type accepts any object.
pub struct BehaviourInfo {
    pub type_id: String,
    pub version: u32,
    /// `package:<pkg>/<path>.dart#<Class>` from the schema, if any.
    pub dart: Option<String>,
    /// False for types known only from the project registry.
    pub has_schema: bool,
    validator: Validator,
}

/// What a tool needs to know about a component type without linking the
/// runtime: its `data` schema and the `x-fynkel` metadata.
pub struct ComponentInfo {
    pub type_id: String,
    pub numeric_id: u32,
    pub authored: bool,
    pub wire_size: u32,
    validator: Validator,
}

impl SchemaSet {
    /// The schemas compiled into this build: the envelope plus every
    /// generated document and component schema (`generated::EMBEDDED_SCHEMAS`).
    /// No `schemas/` directory involved, so shipped runtimes validate too.
    pub fn embedded() -> SchemaSet {
        let loaded = crate::generated::EMBEDDED_SCHEMAS
            .iter()
            .map(|(name, text)| {
                (
                    PathBuf::from(name),
                    serde_json::from_str(text).expect("embedded schema is JSON"),
                )
            })
            .collect();
        SchemaSet::build(loaded).expect("embedded schemas are valid")
    }

    /// Envelope only (every kind reports `FYN-D0101`); for tests.
    pub fn envelope_only() -> SchemaSet {
        SchemaSet::build(Vec::new()).expect("embedded envelope schema is valid")
    }

    /// The embedded schemas plus every `*.schema.json` under `dir`
    /// (recursively): a project's `schemas/` directory, which holds its
    /// generated behaviour schemas. A missing `dir` is not an error.
    pub fn embedded_with(dir: &Path) -> Result<SchemaSet, Diagnostic> {
        SchemaSet::embedded().extended_with(dir)
    }

    /// This set plus every `*.schema.json` under `dir` (recursively; a
    /// missing `dir` adds nothing). A file with the `$id` of a schema
    /// already in the set replaces it. Declared behaviours are kept.
    pub fn extended_with(&self, dir: &Path) -> Result<SchemaSet, Diagnostic> {
        self.extended_with_all(&[dir.to_path_buf()])
    }

    /// [`extended_with`](SchemaSet::extended_with) for several directories
    /// in order (a game's packages, then the game), built once.
    pub fn extended_with_all(&self, dirs: &[PathBuf]) -> Result<SchemaSet, Diagnostic> {
        let mut loaded = self.sources.clone();
        for dir in dirs.iter().filter(|d| d.is_dir()) {
            loaded.extend(read_all(dir)?);
        }
        let mut set = SchemaSet::build(loaded)?;
        for (type_id, version) in &self.declared {
            set.declare_behaviour(type_id, *version);
        }
        for (type_id, version) in &self.declared_data {
            set.declare_data(type_id, *version);
        }
        Ok(set)
    }

    /// Loads every `*.schema.json` under `dir` (recursively).
    pub fn load(dir: &Path) -> Result<SchemaSet, Diagnostic> {
        SchemaSet::build(read_all(dir)?)
    }

    fn build(loaded: Vec<(PathBuf, serde_json::Value)>) -> Result<SchemaSet, Diagnostic> {
        let sources = loaded.clone();
        let envelope_value: serde_json::Value =
            serde_json::from_str(ENVELOPE_SCHEMA).expect("embedded envelope schema");
        let envelope_id = DocumentKind::Scene
            .schema_id()
            .replace("scene.schema.json", "envelope.schema.json");

        let mut by_id: Vec<(String, serde_json::Value)> =
            vec![(envelope_id.clone(), envelope_value.clone())];
        for (path, value) in &loaded {
            let id = value
                .get("$id")
                .and_then(|v| v.as_str())
                .map(str::to_string)
                .unwrap_or_else(|| {
                    format!(
                        "https://fynkel.dev/schemas/{}",
                        path.file_name().unwrap().to_string_lossy()
                    )
                });
            if id == envelope_id {
                by_id[0].1 = value.clone();
            } else if let Some(slot) = by_id.iter_mut().find(|(i, _)| *i == id) {
                slot.1 = value.clone();
            } else {
                by_id.push((id, value.clone()));
            }
        }

        let mut builder = Registry::new().draft(Draft::Draft202012);
        for (id, value) in &by_id {
            builder = builder
                .add(id, Resource::from_contents(value.clone()))
                .map_err(|e| {
                    Diagnostic::error(Code::SCHEMA_UNAVAILABLE, format!("bad schema id {id}: {e}"))
                })?;
        }
        let registry = builder.prepare().map_err(|e| {
            Diagnostic::error(Code::SCHEMA_UNAVAILABLE, format!("schema registry: {e}"))
        })?;

        let compile = |value: &serde_json::Value, id: &str| -> Result<Validator, Diagnostic> {
            jsonschema::draft202012::options()
                .with_registry(&registry)
                .should_validate_formats(true)
                .build(value)
                .map_err(|e| {
                    Diagnostic::error(
                        Code::SCHEMA_UNAVAILABLE,
                        format!("schema {id} does not compile: {e}"),
                    )
                })
        };

        let envelope = compile(&by_id[0].1, &envelope_id)?;
        let mut components = HashMap::new();
        for (id, value) in &by_id {
            let meta = value.get("x-fynkel");
            if meta.and_then(|m| m.get("kind")).and_then(|k| k.as_str()) != Some("component") {
                continue;
            }
            let Some(type_id) = value.get("title").and_then(|t| t.as_str()) else {
                continue;
            };
            let meta = meta.unwrap();
            components.insert(
                type_id.to_string(),
                ComponentInfo {
                    type_id: type_id.to_string(),
                    numeric_id: meta.get("id").and_then(|v| v.as_u64()).unwrap_or(0) as u32,
                    authored: meta
                        .get("authored")
                        .and_then(|v| v.as_bool())
                        .unwrap_or(true),
                    wire_size: meta.get("wireSize").and_then(|v| v.as_u64()).unwrap_or(0) as u32,
                    validator: compile(value, id)?,
                },
            );
        }
        let mut behaviours = HashMap::new();
        let mut data_types = HashMap::new();
        for (id, value) in &by_id {
            let meta = value.get("x-fynkel");
            let map = match meta.and_then(|m| m.get("kind")).and_then(|k| k.as_str()) {
                Some("behaviour") => &mut behaviours,
                Some("data") => &mut data_types,
                _ => continue,
            };
            let meta = meta.unwrap();
            let Some(type_id) = value
                .get("title")
                .and_then(|t| t.as_str())
                .or_else(|| meta.get("id").and_then(|t| t.as_str()))
            else {
                continue;
            };
            map.insert(
                type_id.to_string(),
                BehaviourInfo {
                    type_id: type_id.to_string(),
                    version: meta.get("version").and_then(|v| v.as_u64()).unwrap_or(1) as u32,
                    dart: meta
                        .get("dart")
                        .and_then(|v| v.as_str())
                        .map(str::to_string),
                    has_schema: true,
                    validator: compile(value, id)?,
                },
            );
        }
        let mut asset_fields: HashMap<String, Vec<crate::reference_kinds::AssetField>> =
            HashMap::new();
        for (_, value) in &by_id {
            let meta = value.get("x-fynkel");
            let kind = meta.and_then(|m| m.get("kind")).and_then(|k| k.as_str());
            if !matches!(kind, Some("component") | Some("behaviour") | Some("data")) {
                continue;
            }
            let Some(type_id) = value
                .get("title")
                .and_then(|t| t.as_str())
                .or_else(|| meta.and_then(|m| m.get("id")).and_then(|t| t.as_str()))
            else {
                continue;
            };
            let fields = crate::reference_kinds::asset_fields_of(value);
            if !fields.is_empty() {
                asset_fields.insert(type_id.to_string(), fields);
            }
        }
        for (type_id, field, kinds) in crate::reference_kinds::NATIVE {
            if components.contains_key(*type_id) {
                asset_fields.entry(type_id.to_string()).or_default().push(
                    crate::reference_kinds::AssetField {
                        path: vec![field.to_string()],
                        kinds: kinds.iter().map(|k| k.to_string()).collect(),
                        data: None,
                    },
                );
            }
        }
        let mut validators = HashMap::new();
        let mut missing = Vec::new();
        for kind in DocumentKind::ALL {
            let id = kind.schema_id();
            match by_id.iter().find(|(i, _)| *i == id) {
                Some((_, value)) => {
                    validators.insert(kind, compile(value, &id)?);
                }
                None => missing.push(kind),
            }
        }
        let mut others = HashMap::new();
        for (id, value) in by_id.iter().skip(1) {
            let is_document = DocumentKind::ALL.iter().any(|k| k.schema_id() == *id);
            let kind = value
                .get("x-fynkel")
                .and_then(|m| m.get("kind"))
                .and_then(|k| k.as_str());
            let is_typed = matches!(kind, Some("component") | Some("behaviour") | Some("data"));
            if !is_document && !is_typed {
                others.insert(id.clone(), compile(value, id)?);
            }
        }
        Ok(SchemaSet {
            validators,
            envelope,
            missing,
            components,
            behaviours,
            data_types,
            others,
            sources,
            declared: Vec::new(),
            declared_data: Vec::new(),
            asset_fields,
        })
    }

    /// The fields of `type_id` that name assets of a kind; empty for an
    /// unknown type or one without such fields.
    pub fn asset_fields(&self, type_id: &str) -> &[crate::reference_kinds::AssetField] {
        self.asset_fields.get(type_id).map_or(&[], Vec::as_slice)
    }

    /// Known behaviour type (from a loaded behaviour schema or a
    /// declaration).
    pub fn behaviour(&self, type_id: &str) -> Option<&BehaviourInfo> {
        self.behaviours.get(type_id)
    }

    /// Behaviour types, sorted.
    pub fn behaviour_types(&self) -> Vec<&BehaviourInfo> {
        let mut v: Vec<&BehaviourInfo> = self.behaviours.values().collect();
        v.sort_by(|a, b| a.type_id.cmp(&b.type_id));
        v
    }

    /// Makes `type_id` a known behaviour type without a schema (a project
    /// registry entry of kind `behaviour`): its `data` must be an object
    /// and is otherwise accepted. A loaded schema for the same id wins.
    pub fn declare_behaviour(&mut self, type_id: &str, version: u32) {
        if self.behaviours.contains_key(type_id) {
            return;
        }
        self.declared.push((type_id.to_string(), version));
        let validator = jsonschema::draft202012::options()
            .build(&serde_json::json!({"type": "object"}))
            .expect("constant schema compiles");
        self.behaviours.insert(
            type_id.to_string(),
            BehaviourInfo {
                type_id: type_id.to_string(),
                version,
                dart: None,
                has_schema: false,
                validator,
            },
        );
    }

    /// Declares a data type without a schema (a registry entry of kind
    /// `data`): known, its data accepted as any object. A loaded schema wins.
    pub fn declare_data(&mut self, type_id: &str, version: u32) {
        if self.data_types.contains_key(type_id) {
            return;
        }
        self.declared_data.push((type_id.to_string(), version));
        let validator = jsonschema::draft202012::options()
            .build(&serde_json::json!({"type": "object"}))
            .expect("constant schema compiles");
        self.data_types.insert(
            type_id.to_string(),
            BehaviourInfo {
                type_id: type_id.to_string(),
                version,
                dart: None,
                has_schema: false,
                validator,
            },
        );
    }

    /// Known data asset type (ADR-0027): the same facts a behaviour has.
    pub fn data_type(&self, type_id: &str) -> Option<&BehaviourInfo> {
        self.data_types.get(type_id)
    }

    /// Data asset types, sorted.
    pub fn data_types(&self) -> Vec<&BehaviourInfo> {
        let mut v: Vec<&BehaviourInfo> = self.data_types.values().collect();
        v.sort_by(|a, b| a.type_id.cmp(&b.type_id));
        v
    }

    /// Validates a data asset's `data` against its type's schema (nothing
    /// for an unknown type).
    pub fn validate_data(&self, type_id: &str, data: &Node) -> Vec<Diagnostic> {
        let Some(info) = self.data_types.get(type_id) else {
            return Vec::new();
        };
        let instance = data.to_serde();
        let mut out = Vec::new();
        for err in info.validator.iter_errors(&instance) {
            out.extend(to_diagnostics(&err, &Locator::new(data)));
        }
        sort_by_position(&mut out);
        out
    }

    /// Known component type (from the loaded component schemas).
    pub fn component(&self, type_id: &str) -> Option<&ComponentInfo> {
        self.components.get(type_id)
    }

    /// Component types, sorted.
    pub fn component_types(&self) -> Vec<&ComponentInfo> {
        let mut v: Vec<&ComponentInfo> = self.components.values().collect();
        v.sort_by(|a, b| a.type_id.cmp(&b.type_id));
        v
    }

    /// Validates a component's `data` against its schema (native component
    /// or behaviour). Pointers are relative to `data`; the caller re-anchors
    /// them. Empty for unknown types (the semantic pass reports those).
    pub fn validate_component(&self, type_id: &str, data: &Node) -> Vec<Diagnostic> {
        let validator = match self.components.get(type_id) {
            Some(info) => &info.validator,
            None => match self.behaviours.get(type_id) {
                Some(info) => &info.validator,
                None => return Vec::new(),
            },
        };
        let instance = data.to_serde();
        let mut out = Vec::new();
        for err in validator.iter_errors(&instance) {
            out.extend(to_diagnostics(&err, &Locator::new(data)));
        }
        sort_by_position(&mut out);
        out
    }

    /// Validates a tree against a loaded schema that is not a document
    /// kind's (`https://fynkel.dev/schemas/lock.schema.json`, …); `None`
    /// when no such schema is loaded.
    pub fn validate_schema(&self, schema_id: &str, root: &Node) -> Option<Vec<Diagnostic>> {
        let validator = self.others.get(schema_id)?;
        let instance = root.to_serde();
        let mut out = Vec::new();
        let at = Locator::new(root);
        for err in validator.iter_errors(&instance) {
            out.extend(to_diagnostics(&err, &at));
        }
        sort_by_position(&mut out);
        Some(out)
    }

    /// Kinds without their own schema (validated against the envelope only).
    pub fn missing_kinds(&self) -> &[DocumentKind] {
        &self.missing
    }

    /// Validates a document tree against the kind's schema (or the envelope
    /// schema when the kind has none, with a warning saying so).
    pub fn validate(&self, kind: DocumentKind, root: &Node) -> Vec<Diagnostic> {
        let instance = root.to_serde();
        let mut out = Vec::new();
        let validator = match self.validators.get(&kind) {
            Some(v) => v,
            None => {
                out.push(
                    Diagnostic::new(
                        Code::SCHEMA_UNAVAILABLE,
                        Severity::Warning,
                        format!(
                            "no {} is loaded; only the envelope was validated",
                            kind.schema_file()
                        ),
                    )
                    .with_pointer(""),
                );
                &self.envelope
            }
        };
        let at = Locator::new(root);
        for err in validator.iter_errors(&instance) {
            out.extend(to_diagnostics(&err, &at));
        }
        sort_by_position(&mut out);
        out
    }
}

/// Document order (line, column, pointer) rather than the validator's
/// keyword traversal order, so output is stable and reads top to bottom.
fn sort_by_position(diags: &mut [Diagnostic]) {
    diags.sort_by(|a, b| (a.line, a.column, &a.pointer).cmp(&(b.line, b.column, &b.pointer)));
}

fn read_all(dir: &Path) -> Result<Vec<(PathBuf, serde_json::Value)>, Diagnostic> {
    let mut files = Vec::new();
    collect(dir, &mut files).map_err(|e| {
        Diagnostic::error(
            Code::SCHEMA_UNAVAILABLE,
            format!("cannot read schemas: {e}"),
        )
        .with_document(dir.display().to_string())
    })?;
    files.sort();
    let mut loaded = Vec::new();
    for path in files {
        let text = std::fs::read_to_string(&path).map_err(|e| {
            Diagnostic::error(Code::SCHEMA_UNAVAILABLE, format!("cannot read schema: {e}"))
                .with_document(path.display().to_string())
        })?;
        let value: serde_json::Value = serde_json::from_str(&text).map_err(|e| {
            Diagnostic::error(Code::SCHEMA_UNAVAILABLE, format!("schema is not JSON: {e}"))
                .with_document(path.display().to_string())
                .at(e.line() as u32, e.column() as u32)
        })?;
        loaded.push((path, value));
    }
    Ok(loaded)
}

fn collect(dir: &Path, out: &mut Vec<PathBuf>) -> std::io::Result<()> {
    for entry in std::fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            collect(&path, out)?;
        } else if path.to_string_lossy().ends_with(".schema.json") {
            out.push(path);
        }
    }
    Ok(())
}

fn to_diagnostics(err: &ValidationError<'_>, at: &Locator<'_>) -> Vec<Diagnostic> {
    let base = err.instance_path().as_str().to_string();
    let anchor = |pointer: &str, d: Diagnostic| -> Diagnostic { at.anchor(d, pointer) };
    match err.kind() {
        // One diagnostic per unexpected property, anchored at its key.
        jsonschema::error::ValidationErrorKind::AdditionalProperties { unexpected }
        | jsonschema::error::ValidationErrorKind::UnevaluatedProperties { unexpected } => {
            unexpected
                .iter()
                .map(|key| {
                    let escaped = key.replace('~', "~0").replace('/', "~1");
                    anchor(
                        &format!("{base}/{escaped}"),
                        Diagnostic::error(
                            Code::SCHEMA_VIOLATION,
                            format!("unexpected property {key:?}"),
                        )
                        .with_suggestion("remove it or check the spelling"),
                    )
                })
                .collect()
        }
        _ => vec![anchor(
            &base,
            Diagnostic::error(Code::SCHEMA_VIOLATION, err.to_string())
                .with_suggestion(format!("schema rule {}", err.schema_path())),
        )],
    }
}
