//! Native schema generator (ADR-0012 pipeline (a)):
//! Rust `RecordSchema` registry → JSON Schema, Dart codecs, Rust codecs.
//! Deterministic output; `--check` diffs against the committed files.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use fynkel_contracts::schema::{FieldType, RecordSchema, SchemaKind};
use fynkel_contracts::ABI_VERSION;
use fynkel_core::schema::{schema_fingerprint, ALL};
use serde_json::{json, Value};

pub enum Outcome {
    Written(usize),
    UpToDate,
    Drift(Vec<PathBuf>),
}

pub const DART_OUT: &str = "packages/fynkel/lib/generated/schema.g.dart";
pub const RUST_OUT: &str = "crates/fynkel_wire/src/generated.rs";
pub const JSON_INDEX: &str = "schemas/fynkel.schema.json";

pub fn run(root: &Path, check: bool) -> Result<Outcome, String> {
    let files = generate();
    if check {
        let mut drift = Vec::new();
        for (rel, content) in &files {
            let path = root.join(rel);
            if std::fs::read_to_string(&path).ok().as_deref() != Some(content.as_str()) {
                drift.push(PathBuf::from(rel));
            }
        }
        return Ok(if drift.is_empty() {
            Outcome::UpToDate
        } else {
            Outcome::Drift(drift)
        });
    }
    for (rel, content) in &files {
        let path = root.join(rel);
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
        }
        std::fs::write(&path, content).map_err(|e| format!("{}: {e}", path.display()))?;
    }
    Ok(Outcome::Written(files.len()))
}

/// All outputs as (repo-relative path, content), deterministic order.
pub fn generate() -> Vec<(String, String)> {
    let fp = schema_fingerprint();
    let mut out = vec![
        (JSON_INDEX.to_string(), json_index(fp)),
        (DART_OUT.to_string(), dart(fp)),
        (RUST_OUT.to_string(), rust(fp)),
    ];
    for s in ALL.iter().filter(|s| s.kind == SchemaKind::Component) {
        out.push((
            format!("schemas/components/{}.schema.json", s.name),
            pretty(&json_schema(s)),
        ));
    }
    out
}

fn pretty(v: &Value) -> String {
    let mut s = serde_json::to_string_pretty(v).unwrap();
    s.push('\n');
    s
}

fn rust_ident(s: &RecordSchema) -> &str {
    s.rust_path.rsplit("::").next().unwrap()
}

// ------------------------------------------------------------------ JSON

fn json_index(fp: u64) -> String {
    let records: Vec<Value> = ALL
        .iter()
        .map(|s| {
            let offsets = s.offsets();
            json!({
                "kind": s.kind.name(),
                "id": s.id,
                "name": s.name,
                "rust": s.rust_path,
                "doc": s.doc,
                "size": s.wire_size(),
                "fields": s.fields.iter().zip(offsets).map(|(f, off)| json!({
                    "name": f.name,
                    "type": f.ty.name(),
                    "offset": off,
                    "size": f.ty.wire_size(),
                    "doc": f.doc,
                })).collect::<Vec<_>>(),
            })
        })
        .collect();
    pretty(&json!({
        "$comment": "GENERATED by `fynkel codegen` from the Rust schemas (ADR-0012). Do not edit.",
        "abiVersion": ABI_VERSION,
        "schemaFingerprint": format!("{fp:#018x}"),
        "layout": "little-endian; fields at natural alignment in declaration order; records padded to 8; str = (offset u32, len u32) into the buffer string tail",
        "records": records,
    }))
}

fn json_type(ty: &FieldType) -> Value {
    match ty {
        FieldType::F32 => json!({"type": "number"}),
        FieldType::U32 => json!({"type": "integer", "minimum": 0, "maximum": u32::MAX}),
        FieldType::I32 => json!({"type": "integer", "minimum": i32::MIN, "maximum": i32::MAX}),
        FieldType::U64 | FieldType::Entity => json!({"type": "integer", "minimum": 0}),
        FieldType::OptionalEntity => json!({"type": ["integer", "null"], "minimum": 0}),
        FieldType::Bool => json!({"type": "boolean"}),
        FieldType::Vec3 => {
            json!({"type": "array", "items": {"type": "number"}, "minItems": 3, "maxItems": 3})
        }
        FieldType::Quat => {
            json!({"type": "array", "items": {"type": "number"}, "minItems": 4, "maxItems": 4, "description": "[x, y, z, w]"})
        }
        FieldType::Str => json!({"type": "string"}),
        FieldType::Nested(s) => json!({"$ref": format!("{}.schema.json", s.name)}),
    }
}

fn json_schema(s: &RecordSchema) -> Value {
    let mut props = serde_json::Map::new();
    let mut required = Vec::new();
    for f in s.fields {
        let mut t = json_type(&f.ty);
        if !f.doc.is_empty() {
            t["description"] = Value::String(f.doc.to_string());
        }
        props.insert(f.name.to_string(), t);
        if !matches!(f.ty, FieldType::OptionalEntity) {
            required.push(f.name);
        }
    }
    json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": format!("https://fynkel.dev/schemas/components/{}.schema.json", s.name),
        "$comment": "GENERATED by `fynkel codegen`. Do not edit.",
        "title": s.name,
        "description": s.doc,
        "type": "object",
        "properties": props,
        "required": required,
        "additionalProperties": false,
        "x-fynkel": {"kind": s.kind.name(), "id": s.id, "rust": s.rust_path, "wireSize": s.wire_size()},
    })
}

// ------------------------------------------------------------------ Dart

fn camel(s: &str) -> String {
    let mut out = String::new();
    let mut up = false;
    for c in s.chars() {
        if c == '_' {
            up = true;
        } else if up {
            out.push(c.to_ascii_uppercase());
            up = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn dart_type(ty: &FieldType) -> String {
    match ty {
        FieldType::F32 => "double".into(),
        FieldType::U32 | FieldType::I32 | FieldType::U64 | FieldType::Entity => "int".into(),
        FieldType::OptionalEntity => "int?".into(),
        FieldType::Bool => "bool".into(),
        FieldType::Vec3 => "Vec3".into(),
        FieldType::Quat => "Quat".into(),
        FieldType::Str => "String".into(),
        FieldType::Nested(s) => rust_ident(s).into(),
    }
}

fn dart(fp: u64) -> String {
    let mut o = String::new();
    let _ = writeln!(
        o,
        "// GENERATED by `fynkel codegen` from the Rust component schemas (ADR-0012)."
    );
    let _ = writeln!(o, "// Do not edit. Schema fingerprint {fp:#018x}.");
    let _ = writeln!(o, "//");
    let _ = writeln!(
        o,
        "// ignore_for_file: unused_import, prefer_const_constructors"
    );
    let _ = writeln!(o);
    let _ = writeln!(o, "import 'dart:typed_data';");
    let _ = writeln!(o);
    let _ = writeln!(o, "import '../math.dart';");
    let _ = writeln!(o, "import '../src/wire/support.dart';");
    let _ = writeln!(o);
    let _ = writeln!(
        o,
        "/// Fingerprint of the schemas these codecs implement; must equal the"
    );
    let _ = writeln!(o, "/// native library's `fynkel_schema_fingerprint()`.");
    let _ = writeln!(o, "const int schemaFingerprint = {fp:#x};");
    let _ = writeln!(o, "const int abiVersion = {ABI_VERSION};");
    for s in ALL {
        let name = rust_ident(s);
        let offsets = s.offsets();
        let _ = writeln!(o);
        if !s.doc.is_empty() {
            let _ = writeln!(o, "/// {}", s.doc);
            let _ = writeln!(o, "///");
        }
        let _ = writeln!(
            o,
            "/// `{}` ({}, id {}, {} bytes).",
            s.name,
            s.kind.name(),
            s.id,
            s.wire_size()
        );
        let _ = writeln!(o, "class {name} {{");
        // constructor
        if s.fields.is_empty() {
            let _ = writeln!(o, "  const {name}();");
        } else {
            let _ = writeln!(o, "  const {name}({{");
            for f in s.fields {
                let req = if matches!(f.ty, FieldType::OptionalEntity) {
                    ""
                } else {
                    "required "
                };
                let _ = writeln!(o, "    {req}this.{},", camel(f.name));
            }
            let _ = writeln!(o, "  }});");
        }
        let _ = writeln!(o);
        for f in s.fields {
            if !f.doc.is_empty() {
                let _ = writeln!(o, "  /// {}", f.doc);
            }
            let _ = writeln!(o, "  final {} {};", dart_type(&f.ty), camel(f.name));
        }
        let _ = writeln!(o);
        let _ = writeln!(o, "  static const String schemaName = '{}';", s.name);
        let _ = writeln!(o, "  static const int wireSize = {};", s.wire_size());
        match s.kind {
            SchemaKind::Component => {
                let _ = writeln!(o, "  static const int componentId = {};", s.id);
            }
            SchemaKind::Command => {
                let _ = writeln!(o, "  static const int commandKind = {};", s.id);
            }
            SchemaKind::Event => {
                let _ = writeln!(o, "  static const int eventKind = {};", s.id);
            }
            SchemaKind::Record => {}
        }
        // encode
        let _ = writeln!(o);
        let _ = writeln!(
            o,
            "  /// Writes [wireSize] bytes at [offset]; strings go to [strings]."
        );
        let _ = writeln!(
            o,
            "  void encode(ByteData d, int offset, WireStrings strings) {{"
        );
        for (f, off) in s.fields.iter().zip(&offsets) {
            let v = camel(f.name);
            let line = match f.ty {
                FieldType::F32 => format!("d.setFloat32(offset + {off}, {v}, Endian.little);"),
                FieldType::U32 => format!("d.setUint32(offset + {off}, {v}, Endian.little);"),
                FieldType::I32 => format!("d.setInt32(offset + {off}, {v}, Endian.little);"),
                FieldType::U64 | FieldType::Entity => {
                    format!("d.setUint64(offset + {off}, {v}, Endian.little);")
                }
                FieldType::OptionalEntity => {
                    format!("d.setUint64(offset + {off}, {v} ?? 0, Endian.little);")
                }
                FieldType::Bool => format!("d.setUint8(offset + {off}, {v} ? 1 : 0);"),
                FieldType::Vec3 => format!("writeVec3(d, offset + {off}, {v});"),
                FieldType::Quat => format!("writeQuat(d, offset + {off}, {v});"),
                FieldType::Str => format!("writeWireString(d, offset + {off}, {v}, strings);"),
                FieldType::Nested(_) => format!("{v}.encode(d, offset + {off}, strings);"),
            };
            let _ = writeln!(o, "    {line}");
        }
        let _ = writeln!(o, "  }}");
        // decode
        let _ = writeln!(o);
        let _ = writeln!(
            o,
            "  /// Reads [wireSize] bytes at [offset]; [tail] resolves strings."
        );
        let _ = writeln!(
            o,
            "  static {name} decode(ByteData d, int offset, Uint8List tail) {{"
        );
        if s.fields.is_empty() {
            let _ = writeln!(o, "    return const {name}();");
        } else {
            let _ = writeln!(o, "    return {name}(");
            for (f, off) in s.fields.iter().zip(&offsets) {
                let v = camel(f.name);
                let expr = match f.ty {
                    FieldType::F32 => format!("d.getFloat32(offset + {off}, Endian.little)"),
                    FieldType::U32 => format!("d.getUint32(offset + {off}, Endian.little)"),
                    FieldType::I32 => format!("d.getInt32(offset + {off}, Endian.little)"),
                    FieldType::U64 | FieldType::Entity => {
                        format!("d.getUint64(offset + {off}, Endian.little)")
                    }
                    FieldType::OptionalEntity => {
                        format!("optionalEntity(d.getUint64(offset + {off}, Endian.little))")
                    }
                    FieldType::Bool => format!("d.getUint8(offset + {off}) != 0"),
                    FieldType::Vec3 => format!("readVec3(d, offset + {off})"),
                    FieldType::Quat => format!("readQuat(d, offset + {off})"),
                    FieldType::Str => format!("readWireString(d, offset + {off}, tail)"),
                    FieldType::Nested(n) => {
                        format!("{}.decode(d, offset + {off}, tail)", rust_ident(n))
                    }
                };
                let _ = writeln!(o, "      {v}: {expr},");
            }
            let _ = writeln!(o, "    );");
        }
        let _ = writeln!(o, "  }}");
        // equality + toString
        let _ = writeln!(o);
        let _ = writeln!(o, "  @override");
        let _ = writeln!(o, "  bool operator ==(Object other) =>");
        let _ = write!(o, "      other is {name}");
        for f in s.fields {
            let v = camel(f.name);
            let _ = write!(o, " && other.{v} == {v}");
        }
        let _ = writeln!(o, ";");
        let _ = writeln!(o);
        let _ = writeln!(o, "  @override");
        if s.fields.is_empty() {
            let _ = writeln!(o, "  int get hashCode => schemaName.hashCode;");
        } else {
            let _ = writeln!(
                o,
                "  int get hashCode => Object.hashAll([{}]);",
                s.fields
                    .iter()
                    .map(|f| camel(f.name))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
        }
        let _ = writeln!(o);
        let _ = writeln!(o, "  @override");
        let _ = write!(o, "  String toString() => '{name}(");
        let parts: Vec<String> = s
            .fields
            .iter()
            .map(|f| {
                let v = camel(f.name);
                format!("{v}: ${v}")
            })
            .collect();
        let _ = write!(o, "{}", parts.join(", "));
        let _ = writeln!(o, ")';");
        let _ = writeln!(o, "}}");
    }
    o
}

// ------------------------------------------------------------------ Rust

fn rust(fp: u64) -> String {
    let mut o = String::new();
    let _ = writeln!(
        o,
        "// GENERATED by `fynkel codegen` from the Rust component schemas (ADR-0012)."
    );
    let _ = writeln!(o, "// Do not edit. Schema fingerprint {fp:#018x}.");
    let _ = writeln!(o);
    let _ = writeln!(o, "use crate::*;");
    let _ = writeln!(o);
    let _ = writeln!(
        o,
        "/// Derived from `fynkel_core::schema::ALL`; `fynkel codegen --check` guards drift."
    );
    let _ = writeln!(o, "pub const SCHEMA_FINGERPRINT: u64 = {fp:#018x};");
    for s in ALL {
        let path = format!("::{}", s.rust_path);
        let offsets = s.offsets();
        let _ = writeln!(o);
        let _ = writeln!(o, "/// `{}` ({}, id {}).", s.name, s.kind.name(), s.id);
        let _ = writeln!(o, "impl WireRecord for {path} {{");
        let _ = writeln!(o, "    const SIZE: usize = {};", s.wire_size());
        let _ = writeln!(
            o,
            "    fn encode(&self, out: &mut [u8], strings: &mut StringTable) {{"
        );
        let _ = writeln!(o, "        let out = &mut out[..Self::SIZE];");
        let _ = writeln!(o, "        let _ = (&out, &strings);");
        for (f, off) in s.fields.iter().zip(&offsets) {
            let v = format!("self.{}", f.name);
            let line = match f.ty {
                FieldType::F32 => format!("put_f32(out, {off}, {v});"),
                FieldType::U32 => format!("put_u32(out, {off}, {v});"),
                FieldType::I32 => format!("put_i32(out, {off}, {v});"),
                FieldType::U64 => format!("put_u64(out, {off}, {v});"),
                FieldType::Entity => format!("put_entity(out, {off}, {v});"),
                FieldType::OptionalEntity => format!("put_opt_entity(out, {off}, {v});"),
                FieldType::Bool => format!("put_bool(out, {off}, {v});"),
                FieldType::Vec3 => format!("put_vec3(out, {off}, {v});"),
                FieldType::Quat => format!("put_quat(out, {off}, {v});"),
                FieldType::Str => format!("put_str(out, {off}, &{v}, strings);"),
                FieldType::Nested(n) => format!(
                    "<::{} as WireRecord>::encode(&{v}, &mut out[{off}..{}], strings);",
                    n.rust_path,
                    off + n.wire_size()
                ),
            };
            let _ = writeln!(o, "        {line}");
        }
        let _ = writeln!(o, "    }}");
        let _ = writeln!(
            o,
            "    fn decode(b: &[u8], tail: &[u8]) -> Result<Self, WireError> {{"
        );
        let _ = writeln!(o, "        check_len(b, Self::SIZE)?;");
        let _ = writeln!(o, "        let _ = tail;");
        if s.fields.is_empty() {
            let _ = writeln!(o, "        Ok(Self)");
        } else {
            let _ = writeln!(o, "        Ok(Self {{");
            for (f, off) in s.fields.iter().zip(&offsets) {
                let expr = match f.ty {
                    FieldType::F32 => format!("get_f32(b, {off})"),
                    FieldType::U32 => format!("get_u32(b, {off})"),
                    FieldType::I32 => format!("get_i32(b, {off})"),
                    FieldType::U64 => format!("get_u64(b, {off})"),
                    FieldType::Entity => format!("get_entity(b, {off})"),
                    FieldType::OptionalEntity => format!("get_opt_entity(b, {off})"),
                    FieldType::Bool => format!("get_bool(b, {off})"),
                    FieldType::Vec3 => format!("get_vec3(b, {off})"),
                    FieldType::Quat => format!("get_quat(b, {off})"),
                    FieldType::Str => format!("get_str(b, {off}, tail)?"),
                    FieldType::Nested(n) => format!(
                        "<::{} as WireRecord>::decode(&b[{off}..{}], tail)?",
                        n.rust_path,
                        off + n.wire_size()
                    ),
                };
                let _ = writeln!(o, "            {}: {expr},", f.name);
            }
            let _ = writeln!(o, "        }})");
        }
        let _ = writeln!(o, "    }}");
        let _ = writeln!(o, "}}");
    }
    o
}
