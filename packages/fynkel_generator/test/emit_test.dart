// The emitters are pure functions of the model: stable identifiers, sorted
// output, the field converters each kind needs, and schemas that say what
// the Dart types accept.

import 'dart:convert';

import 'package:fynkel_generator/fynkel_generator.dart';
import 'package:test/test.dart';

const spinner = BehaviourClass(
  id: 'game.Spinner',
  version: 1,
  className: 'Spinner',
  libraryUri: 'package:demo/spinner.dart',
  doc: 'Rotates its object.',
  fields: [
    ExposedField(name: 'speed', kind: FieldKind.number, defaultValue: 1.0, hasDefault: true, min: 0, step: 0.1),
    ExposedField(name: 'axis', kind: FieldKind.vec3, defaultValue: [0.0, 1.0, 0.0], hasDefault: true),
    ExposedField(name: 'showcase', kind: FieldKind.assetRef, nullable: true, label: 'Showcase'),
    ExposedField(name: 'laps', kind: FieldKind.integer, defaultValue: 3, hasDefault: true, max: 10),
    ExposedField(name: 'title', kind: FieldKind.string, defaultValue: "it's", hasDefault: true),
    ExposedField(name: 'pose', kind: FieldKind.quat),
    ExposedField(name: 'on', kind: FieldKind.boolean, nullable: true, defaultValue: null, hasDefault: true),
  ],
);

const blinker = BehaviourClass(
  id: 'game.Blinker',
  version: 2,
  className: 'Blinker',
  libraryUri: 'package:demo/other/blinker.dart',
  fields: [],
);

void main() {
  test('identifiers derive from the type id', () {
    expect(identifierFor('game.Spinner'), 'gameSpinnerType');
    expect(identifierFor('my_game.ui.HealthBar'), 'myGameUiHealthBarType');
    expect(identifierFor('3d.Thing'), r'$3dThingType');
    expect(schemaIdFor('game.Spinner'), 'https://fynkel.dev/schemas/behaviours/game.Spinner.schema.json');
  });

  test('emitDart: sorted types, one import prefix per library, only the converters used', () {
    final src = emitDart('demo', [spinner, blinker]);
    expect(src, startsWith('// GENERATED by fynkel_generator'));
    expect(src, contains("import 'package:demo/other/blinker.dart' as _lib0;"));
    expect(src, contains("import 'package:demo/spinner.dart' as _lib1;"));
    expect(src.indexOf('gameBlinkerType =>'), lessThan(src.indexOf('gameSpinnerType =>')));
    expect(src, contains('create: _lib1.Spinner.new'));
    expect(src, contains('fields: const []'));
    expect(src, contains("defaultValue: 'it\\'s'"));
    expect(src, contains('defaultValue: const [0.0, 1.0, 0.0]'));
    expect(src, contains('max: 10'));
    expect(src, contains('set: (b, v) => (b as _lib1.Spinner).speed = _double(v)'));
    expect(src, contains('set: (b, v) => (b as _lib1.Spinner).laps = _int(v)'));
    expect(src, contains('(b as _lib1.Spinner).showcase = _orNull(v, _assetRef)'));
    expect(src, contains('(b as _lib1.Spinner).on = _orNull(v, (v) => v as bool)'));
    expect(src, contains('get: (b) => _quatJson((b as _lib1.Spinner).pose)'));
    expect(src, contains('behaviourTypes => List.unmodifiable([gameBlinkerType, gameSpinnerType])'));
    expect(src, contains('void registerBehaviours(BehaviourRegistry registry, {bool replace = false})'));
    for (final helper in ['_double(', '_int(', '_vec3(', '_quat(', '_assetRef(', '_orNull<T>(']) {
      expect(src, contains(helper));
    }
    // A package with only scalars gets only scalar converters.
    final scalar = emitDart('demo', [
      const BehaviourClass(
        id: 'a.B',
        version: 1,
        className: 'B',
        libraryUri: 'package:demo/b.dart',
        fields: [ExposedField(name: 'x', kind: FieldKind.boolean)],
      ),
    ]);
    expect(scalar, isNot(contains('_vec3')));
    expect(scalar, isNot(contains('_orNull')));
    expect(scalar, isNot(contains('// JSON ↔ field value converters.')));
    expect(scalar, contains("(b as _lib0.B).x = v as bool"));
    // Same input, same bytes.
    expect(emitDart('demo', [blinker, spinner]), src);
  });

  test('schemaFor: fields optional, unknown keys rejected, nullable and bounds honoured', () {
    final s = schemaFor(spinner);
    expect(s[r'$id'], schemaIdFor('game.Spinner'));
    expect(s['title'], 'game.Spinner');
    expect(s['description'], 'Rotates its object.');
    expect(s['additionalProperties'], false);
    expect(s.containsKey('required'), isFalse);
    expect(s['x-fynkel'], {'kind': 'behaviour', 'id': 'game.Spinner', 'version': 1, 'dart': 'package:demo/spinner.dart#Spinner'});
    final p = s['properties'] as Map<String, Object?>;
    expect(p['speed'], {
      'type': 'number',
      'minimum': 0,
      'default': 1.0,
      'x-fynkel': {'type': 'number', 'min': 0, 'step': 0.1},
    });
    expect((p['laps'] as Map)['maximum'], 10);
    expect((p['axis'] as Map)['minItems'], 3);
    expect((p['pose'] as Map)['maxItems'], 4);
    expect((p['showcase'] as Map)['anyOf'], [
      {r'$ref': r'https://fynkel.dev/schemas/envelope.schema.json#/$defs/assetRef'},
      {'type': 'null'},
    ]);
    expect((p['on'] as Map)['type'], ['boolean', 'null']);
    expect((p['on'] as Map)['default'], isNull);
    expect((p['on'] as Map).containsKey('default'), isTrue);
    expect(schemaFor(blinker)['properties'], isEmpty);
  });

  test('the ADR-0018 hints reach x-fynkel and the metadata, only when given; kinds are checked', () {
    const turret = BehaviourClass(
      id: 'game.Turret',
      version: 1,
      className: 'Turret',
      libraryUri: 'package:demo/turret.dart',
      doc: 'Shoots.',
      icon: 'gps_fixed',
      category: 'Gameplay',
      fields: [
        ExposedField(name: 'armed', kind: FieldKind.boolean, defaultValue: true, hasDefault: true, group: 'Firing', order: 0),
        ExposedField(
          name: 'yaw',
          kind: FieldKind.number,
          defaultValue: 0.0,
          hasDefault: true,
          label: 'Yaw',
          tooltip: 'Where it points',
          min: -3.14,
          max: 3.14,
          step: 0.01,
          group: 'Aim',
          order: 2,
          header: 'Aiming',
          unit: 'deg',
          displayKind: 'angle',
          showIf: 'armed',
        ),
        ExposedField(name: 'tint', kind: FieldKind.vec3, displayKind: 'color', readOnly: true),
        ExposedField(name: 'shell', kind: FieldKind.assetRef, displayKind: 'asset(prefab)', hidden: true),
      ],
    );
    final s = schemaFor(turret);
    expect((s['x-fynkel'] as Map)['icon'], 'gps_fixed');
    expect((s['x-fynkel'] as Map)['category'], 'Gameplay');
    final p = s['properties'] as Map<String, Object?>;
    expect((p['yaw'] as Map)['x-fynkel'], {
      'type': 'number',
      'label': 'Yaw',
      'tooltip': 'Where it points',
      'min': -3.14,
      'max': 3.14,
      'step': 0.01,
      'group': 'Aim',
      'order': 2,
      'header': 'Aiming',
      'unit': 'deg',
      'kind': 'angle',
      'showIf': 'armed',
    });
    expect((p['yaw'] as Map)['minimum'], -3.14);
    expect((p['armed'] as Map)['x-fynkel'], {'type': 'boolean', 'group': 'Firing', 'order': 0});
    expect((p['tint'] as Map)['x-fynkel'], {'type': 'vec3', 'kind': 'color', 'readOnly': true});
    expect((p['shell'] as Map)['x-fynkel'], {'type': 'assetRef', 'kind': 'asset(prefab)', 'hidden': true});
    // A class without hints emits exactly what it did before ADR-0018.
    final plain = (schemaFor(spinner)['properties'] as Map)['speed'] as Map;
    expect(plain['x-fynkel'], {'type': 'number', 'min': 0, 'step': 0.1});
    expect((schemaFor(spinner)['x-fynkel'] as Map).containsKey('icon'), isFalse);

    final doc = jsonDecode(emitJson('demo', [turret])) as Map<String, Object?>;
    final t = (doc['behaviours'] as List).single as Map;
    expect(t['icon'], 'gps_fixed');
    expect(t['category'], 'Gameplay');
    final yaw = (t['fields'] as List)[1] as Map;
    expect(yaw['kind'], 'angle');
    expect(yaw['unit'], 'deg');
    expect(yaw['showIf'], 'armed');
    expect(yaw['group'], 'Aim');
    expect(((t['fields'] as List)[2] as Map)['readOnly'], true);
    expect(((t['fields'] as List)[0] as Map).containsKey('readOnly'), isFalse);

    expect(exposeKindProblem('color', FieldKind.vec3), isNull);
    expect(exposeKindProblem('color', FieldKind.number), contains('Vec3'));
    expect(exposeKindProblem('asset(mesh)', FieldKind.assetRef), isNull);
    expect(exposeKindProblem('asset(font)', FieldKind.assetRef), contains('unknown asset kind'));
    expect(exposeKindProblem('asset(mesh)', FieldKind.string), contains('AssetRef'));
    expect(exposeKindProblem('entity', FieldKind.string), isNull);
    expect(exposeKindProblem('multiline', FieldKind.integer), contains('String'));
    expect(exposeKindProblem('angle', FieldKind.number), isNull);
    expect(exposeKindProblem('slider', FieldKind.integer), isNull);
    expect(exposeKindProblem('layerMask', FieldKind.number), contains('int'));
    expect(exposeKindProblem('button', FieldKind.number), contains('unknown kind'));
  });

  test('@Gizmo reaches x-fynkel beside the hints; a List<Vec3> is an array of triples', () {
    const radius = ExposedField(name: 'reach', kind: FieldKind.number, gizmo: GizmoSpec(shape: 'radius'));
    const path = ExposedField(
      name: 'waypoints',
      kind: FieldKind.vec3List,
      defaultValue: [
        [0.0, 0.0, 0.0],
      ],
      hasDefault: true,
      gizmo: GizmoSpec(shape: 'path', color: 0xFFFF0000, when: 'always', space: 'world'),
    );
    const cone = ExposedField(name: 'length', kind: FieldKind.number, gizmo: GizmoSpec(shape: 'cone', angle: 'spread'));
    const spread = ExposedField(name: 'spread', kind: FieldKind.number);
    const patrol = BehaviourClass(
      id: 'game.Patrol',
      version: 1,
      className: 'Patrol',
      libraryUri: 'package:demo/patrol.dart',
      fields: [cone, radius, spread, path],
    );
    final p = schemaFor(patrol)['properties'] as Map<String, Object?>;
    expect((p['reach'] as Map)['x-fynkel'], {
      'type': 'number',
      'gizmo': {'shape': 'radius'},
    });
    expect((p['length'] as Map)['x-fynkel'], {
      'type': 'number',
      'gizmo': {'shape': 'cone', 'angle': 'spread'},
    });
    final w = p['waypoints'] as Map;
    expect(w['type'], 'array');
    expect(w['items'], {
      'type': 'array',
      'items': {'type': 'number'},
      'minItems': 3,
      'maxItems': 3,
    });
    expect(w['x-fynkel'], {
      'type': 'vec3List',
      'gizmo': {'shape': 'path', 'color': 0xFFFF0000, 'when': 'always', 'space': 'world'},
    });
    final src = emitDart('demo', [patrol]);
    expect(src, contains('(b as _lib0.Patrol).waypoints = _vec3List(v)'));
    expect(src, contains('get: (b) => _vec3ListJson((b as _lib0.Patrol).waypoints)'));
    expect(src, contains('Vec3 _vec3(Object? v)'));
    expect(src, isNot(contains('_vec3Json(')), reason: 'no Vec3 field');
    expect(src, matches(RegExp(r'defaultValue: const \[\s*const \[0\.0, 0\.0, 0\.0\],?\s*\]')));

    const fields = [cone, radius, spread, path];
    for (final f in [cone, radius, path]) {
      expect(gizmoProblem(f.gizmo!, f, fields), isNull);
    }
    expect(gizmoProblem(const GizmoSpec(shape: 'radius'), path, fields), contains('double'));
    expect(gizmoProblem(const GizmoSpec(shape: 'box'), radius, fields), contains('Vec3'));
    expect(gizmoProblem(const GizmoSpec(shape: 'lineTo'), radius, fields), contains('String'));
    expect(gizmoProblem(const GizmoSpec(shape: 'cone', angle: 'nope'), cone, fields), contains("angle 'nope'"));
    expect(gizmoProblem(const GizmoSpec(shape: 'cone', angle: 'length'), cone, fields), contains('another'));
  });

  test('List<T> (ADR-0027 §5): each item converted both ways, the item hints on the items schema', () {
    const wave = BehaviourClass(
      id: 'game.Wave',
      version: 1,
      className: 'Wave',
      libraryUri: 'package:demo/wave.dart',
      fields: [
        ExposedField(
          name: 'delays',
          kind: FieldKind.list,
          item: FieldKind.number,
          defaultValue: [0.5, 1.0],
          hasDefault: true,
          min: 0,
          unit: 's',
          label: 'Delays',
        ),
        ExposedField(name: 'counts', kind: FieldKind.list, item: FieldKind.integer, nullable: true),
        ExposedField(name: 'names', kind: FieldKind.list, item: FieldKind.string),
        ExposedField(name: 'turns', kind: FieldKind.list, item: FieldKind.quat),
        ExposedField(name: 'sounds', kind: FieldKind.list, item: FieldKind.assetRef, displayKind: 'asset(audio)'),
        ExposedField(
          name: 'modes',
          kind: FieldKind.list,
          item: FieldKind.enumeration,
          typeLibrary: 'package:demo/modes.dart',
          typeName: 'Mode',
          enumValues: ['idle', 'aim'],
        ),
      ],
    );
    final src = emitDart('demo', [wave]);
    const w = '(b as _lib1.Wave)';
    expect(src, contains('get: (b) => $w.delays.cast<Object?>().toList()'), reason: 'a copy, never the live list');
    expect(src, contains('$w.delays = [for (final x in v as List) _double(x)]'));
    expect(src, contains('get: (b) => $w.counts?.cast<Object?>().toList()'));
    expect(src, contains('$w.counts = v == null ? null : [for (final x in v as List) _int(x)]'));
    expect(src, contains('$w.names = [for (final x in v as List) x as String]'));
    expect(src, contains('get: (b) => [for (final x in $w.turns) _quatJson(x)]'));
    expect(src, contains('$w.turns = [for (final x in v as List) _quat(x)]'));
    expect(src, contains('get: (b) => [for (final x in $w.sounds) _assetRefJson(x)]'));
    expect(src, contains('$w.sounds = [for (final x in v as List) _assetRef(x)]'));
    expect(src, contains('get: (b) => [for (final x in $w.modes) x.name]'));
    expect(src, contains('for (final x in v as List) _lib0.Mode.values.byName(x as String)'));
    expect(src, isNot(contains('_orNull')), reason: 'a nullable list converts inline');

    final p = schemaFor(wave)['properties'] as Map<String, Object?>;
    expect(p['delays'], {
      'type': 'array',
      'items': {
        'type': 'number',
        'minimum': 0,
        'x-fynkel': {'type': 'number', 'min': 0, 'unit': 's'},
      },
      'default': [0.5, 1.0],
      'x-fynkel': {'type': 'list', 'label': 'Delays', 'items': 'number'},
    });
    expect((p['counts'] as Map)['type'], ['array', 'null']);
    expect((p['turns'] as Map)['items'], containsPair('minItems', 4));
    expect((p['sounds'] as Map)['items'], {
      r'$ref': r'https://fynkel.dev/schemas/envelope.schema.json#/$defs/assetRef',
      'x-fynkel': {'type': 'assetRef', 'kind': 'asset(audio)'},
    });
    expect((p['sounds'] as Map)['x-fynkel'], {'type': 'list', 'items': 'assetRef'},
        reason: "the kind hint is the item's, or the Inspector would take the list for one asset");
    expect((p['modes'] as Map)['items'], containsPair('enum', ['idle', 'aim']));

    expect(exposeKindProblem('asset(audio)', FieldKind.assetRef), isNull);
    expect(exposeKindProblem('asset(physics_material)', FieldKind.assetRef), isNull);
  });

  test('emitJson: metadata plus schema per type, sorted, JSON-parseable', () {
    final text = emitJson('demo', [spinner, blinker]);
    final doc = jsonDecode(text) as Map<String, Object?>;
    expect(doc['package'], 'demo');
    final list = doc['behaviours'] as List;
    expect(list.map((b) => (b as Map)['id']), ['game.Blinker', 'game.Spinner']);
    final sp = list[1] as Map;
    expect(sp['class'], 'Spinner');
    expect(sp['library'], 'package:demo/spinner.dart');
    final fields = sp['fields'] as List;
    expect(fields.map((f) => (f as Map)['name']), ['speed', 'axis', 'showcase', 'laps', 'title', 'pose', 'on']);
    expect((fields[2] as Map)['nullable'], true);
    expect((fields[2] as Map)['label'], 'Showcase');
    expect((fields[5] as Map).containsKey('default'), isFalse);
    expect(sp['schema'], schemaFor(spinner));
    expect(text, endsWith('\n'));
  });

  test('enums, GameObject and script references: the enum by name, a reference resolved by the world', () {
    const turret = BehaviourClass(
      id: 'game.Turret',
      version: 1,
      className: 'Turret',
      libraryUri: 'package:demo/turret.dart',
      fields: [
        ExposedField(
          name: 'mode',
          kind: FieldKind.enumeration,
          typeLibrary: 'package:demo/modes.dart',
          typeName: 'Mode',
          enumValues: ['idle', 'aim', 'fire'],
          defaultValue: 'aim',
          hasDefault: true,
        ),
        ExposedField(
          name: 'fallback',
          kind: FieldKind.enumeration,
          nullable: true,
          typeLibrary: 'package:demo/modes.dart',
          typeName: 'Mode',
          enumValues: ['idle', 'aim', 'fire'],
        ),
        ExposedField(name: 'target', kind: FieldKind.gameObject, nullable: true),
        ExposedField(
          name: 'spinner',
          kind: FieldKind.behaviour,
          nullable: true,
          typeLibrary: 'package:demo/spinner.dart',
          typeName: 'Spinner',
          behaviourId: 'game.Spinner',
        ),
      ],
    );
    final src = emitDart('demo', [turret]);
    // The enum's and the script's libraries are imported with the rest.
    expect(src, contains("import 'package:demo/modes.dart' as _lib0;"));
    expect(src, contains("import 'package:demo/spinner.dart' as _lib1;"));
    expect(src, contains("import 'package:demo/turret.dart' as _lib2;"));
    expect(src, contains('get: (b) => (b as _lib2.Turret).mode.name'));
    expect(src, contains('(b as _lib2.Turret).mode = _lib0.Mode.values.byName(v as String)'));
    expect(src, contains('get: (b) => (b as _lib2.Turret).fallback?.name'));
    expect(src, contains('(b as _lib2.Turret).fallback = _orNull(v, (v) => _lib0.Mode.values.byName(v as String))'));
    expect(src, contains("type: 'gameObject'"));
    expect(src, contains('get: (b) => referenceJson((b as _lib2.Turret).target)'));
    expect(src, contains('target: (b) => (b as _lib2.Turret).target,'));
    expect(src, contains('(b as _lib2.Turret).target = v as GameObject?'));
    expect(src, contains('(b as _lib2.Turret).spinner = v as _lib1.Spinner?'));

    final props = schemaFor(turret)['properties'] as Map<String, Object?>;
    expect(props['mode'], containsPair('enum', ['idle', 'aim', 'fire']));
    expect((props['mode'] as Map)['x-fynkel'], {'type': 'enum'});
    expect(props['fallback'], containsPair('enum', ['idle', 'aim', 'fire', null]));
    expect(props['target'], containsPair('required', ['entity']));
    expect(props['target'], containsPair('type', ['object', 'null']));
    expect(props['spinner'], containsPair('required', ['entity', 'component']));
    expect((props['spinner'] as Map)['x-fynkel'], {'type': 'behaviour', 'nullable': true, 'behaviour': 'game.Spinner'});
  });

  test('errors name the declaration', () {
    final e = BehaviourGenerationError('bad', library: 'package:demo/a.dart', member: 'A.x');
    expect(e.toString(), 'fynkel_generator: package:demo/a.dart A.x: bad');
    expect(BehaviourGenerationError('bad').toString(), 'fynkel_generator: bad');
  });
