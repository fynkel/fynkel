/// Emission: `List<BehaviourClass>` → the generated Dart, the metadata JSON
/// and the per-type JSON Schema. Pure functions of their input, sorted by
/// type id, so the output is byte-stable across machines and runs.
library;

import 'dart:convert';

import 'package:dart_style/dart_style.dart';

import 'model.dart';

const String generatedComment = 'GENERATED by fynkel_generator (`fynkel codegen`). Do not edit.';
const String envelopeSchemaId = 'https://fynkel.dev/schemas/envelope.schema.json';

/// `$id` of a behaviour type's schema.
String schemaIdFor(String typeId) => 'https://fynkel.dev/schemas/behaviours/$typeId.schema.json';

/// The Dart identifier holding a type's `BehaviourType`: `game.Spinner` →
/// `gameSpinnerType`.
String identifierFor(String typeId) {
  final parts = typeId.split(RegExp(r'[^A-Za-z0-9]+')).where((p) => p.isNotEmpty).toList();
  if (parts.isEmpty) return r'$Type';
  final b = StringBuffer();
  for (var i = 0; i < parts.length; i++) {
    final p = parts[i];
    b.write(i == 0 ? p[0].toLowerCase() + p.substring(1) : p[0].toUpperCase() + p.substring(1));
  }
  var s = b.toString();
  if (RegExp(r'^[0-9]').hasMatch(s)) s = '\$$s';
  return '${s}Type';
}

List<BehaviourClass> _sorted(List<BehaviourClass> classes) {
  final out = classes.toList()..sort((a, b) => a.id.compareTo(b.id));
  return out;
}

// ------------------------------------------------------------------- Dart

/// `lib/generated/behaviours.g.dart` for [package].
String emitDart(String package, List<BehaviourClass> classes) {
  final sorted = _sorted(classes);
  final libraries = {
    for (final c in sorted) ...[c.libraryUri, for (final f in c.fields) ?f.typeLibrary],
  }.toList()
    ..sort();
  final prefix = {for (var i = 0; i < libraries.length; i++) libraries[i]: '_lib$i'};
  final names = <String, String>{};
  final used = <String>{};
  for (final c in sorted) {
    var name = identifierFor(c.id);
    var n = 2;
    while (!used.add(name)) {
      name = '${identifierFor(c.id)}$n';
      n++;
    }
    names[c.id] = name;
  }
  final kinds = <FieldKind>{};
  var anyNullable = false;
  for (final c in sorted) {
    for (final f in c.fields) {
      kinds.add(f.kind);
      anyNullable |= f.nullable && !f.kind.isReference;
    }
  }

  final o = StringBuffer();
  o.writeln('// $generatedComment');
  o.writeln('// Behaviour registration for package `$package` (ADR-0012 pipeline (b)).');
  o.writeln('//');
  o.writeln('// ignore_for_file: type=lint, unused_element');
  o.writeln();
  o.writeln("import 'package:fynkel/fynkel.dart';");
  for (final lib in libraries) {
    o.writeln("import '$lib' as ${prefix[lib]};");
  }
  o.writeln();
  // Getters, not top-level finals: a hot reload keeps a final that was
  // already read, so a behaviour added (or a field changed) since the
  // editor started would never register; a getter is evaluated again.
  for (final c in sorted) {
    final cls = '${prefix[c.libraryUri]}.${c.className}';
    o.writeln('/// `${c.id}` v${c.version} → [$cls].');
    o.writeln('BehaviourType get ${names[c.id]} => BehaviourType(');
    o.writeln("  id: '${_dartString(c.id)}',");
    o.writeln('  version: ${c.version},');
    o.writeln('  create: $cls.new,');
    if (c.fields.isEmpty) {
      o.writeln('  fields: const [],');
    } else {
      o.writeln('  fields: [');
      for (final f in c.fields) {
        o.writeln('    BehaviourField(');
        o.writeln("      name: '${_dartString(f.name)}',");
        o.writeln("      type: '${f.kind.typeName}',");
        if (f.hasDefault) o.writeln('      defaultValue: ${_dartLiteral(f.defaultValue)},');
        if (f.label != null) o.writeln("      label: '${_dartString(f.label!)}',");
        if (f.tooltip != null) o.writeln("      tooltip: '${_dartString(f.tooltip!)}',");
        if (f.min != null) o.writeln('      min: ${_dartLiteral(f.min)},');
        if (f.max != null) o.writeln('      max: ${_dartLiteral(f.max)},');
        if (f.step != null) o.writeln('      step: ${_dartLiteral(f.step)},');
        o.writeln('      get: (b) => ${_getter(f, cls)},');
        final type = f.typeName == null ? null : '${prefix[f.typeLibrary]}.${f.typeName}';
        o.writeln('      set: (b, v) => (b as $cls).${f.name} = ${_setter(f, type)},');
        o.writeln('    ),');
      }
      o.writeln('  ],');
    }
    o.writeln(');');
    o.writeln();
  }
  o.writeln('/// Every `@FynkelBehaviour` type of package `$package`, by id.');
  o.writeln('List<BehaviourType> get behaviourTypes => List.unmodifiable([');
  for (final c in sorted) {
    o.writeln('  ${names[c.id]},');
  }
  o.writeln(']);');
  o.writeln();
  o.writeln('/// Registers every type of this package in [registry].');
  o.writeln('void registerBehaviours(BehaviourRegistry registry, {bool replace = false}) {');
  o.writeln('  for (final t in behaviourTypes) {');
  o.writeln('    registry.register(t, replace: replace);');
  o.writeln('  }');
  o.writeln('}');

  // Converters, only the ones some field uses.
  final helpers = <String>[];
  if (kinds.contains(FieldKind.number)) {
    helpers.add('double _double(Object? v) => (v as num).toDouble();');
  }
  if (kinds.contains(FieldKind.integer)) {
    helpers.add('''
int _int(Object? v) {
  if (v is int) return v;
  final d = v as double;
  if (d != d.truncateToDouble()) throw FormatException('expected an integer, got \$d');
  return d.toInt();
}''');
  }
  if (kinds.contains(FieldKind.vec3) || kinds.contains(FieldKind.vec3List)) {
    helpers.add('''
Vec3 _vec3(Object? v) {
  final l = (v as List).cast<num>();
  if (l.length != 3) throw FormatException('expected [x, y, z], got \${l.length} items');
  return Vec3(l[0].toDouble(), l[1].toDouble(), l[2].toDouble());
}''');
  }
  if (kinds.contains(FieldKind.vec3)) {
    helpers.add('List<double>? _vec3Json(Vec3? v) => v == null ? null : [v.x, v.y, v.z];');
  }
  if (kinds.contains(FieldKind.vec3List)) {
    helpers.add('''
List<Vec3> _vec3List(Object? v) => [for (final p in v as List) _vec3(p)];

List<List<double>>? _vec3ListJson(List<Vec3>? v) => v == null ? null : [for (final p in v) [p.x, p.y, p.z]];''');
  }
  if (kinds.contains(FieldKind.quat)) {
    helpers.add('''
Quat _quat(Object? v) {
  final l = (v as List).cast<num>();
  if (l.length != 4) throw FormatException('expected [x, y, z, w], got \${l.length} items');
  return Quat(l[0].toDouble(), l[1].toDouble(), l[2].toDouble(), l[3].toDouble());
}

List<double>? _quatJson(Quat? v) => v == null ? null : [v.x, v.y, v.z, v.w];''');
  }
  if (kinds.contains(FieldKind.assetRef)) {
    helpers.add('''
AssetRef _assetRef(Object? v) {
  final m = v as Map;
  return AssetRef(m['asset'] as String, sub: m['sub'] as String?);
}

Map<String, Object?>? _assetRefJson(AssetRef? r) =>
    r == null ? null : {'asset': r.asset, if (r.sub != null) 'sub': r.sub};''');
  }
  if (anyNullable) {
    helpers.add('T? _orNull<T>(Object? v, T Function(Object?) convert) => v == null ? null : convert(v);');
  }
  if (helpers.isNotEmpty) {
    o.writeln();
    o.writeln('// JSON ↔ field value converters.');
    for (final h in helpers) {
      o.writeln(h);
      o.writeln();
    }
  }
  return DartFormatter(languageVersion: DartFormatter.latestLanguageVersion, pageWidth: 100).format(o.toString());
}

String _getter(ExposedField f, String cls) {
  final read = '(b as $cls).${f.name}';
  return switch (f.kind) {
    FieldKind.vec3 => '_vec3Json($read)',
    FieldKind.quat => '_quatJson($read)',
    FieldKind.assetRef => '_assetRefJson($read)',
    FieldKind.vec3List => '_vec3ListJson($read)',
    FieldKind.enumeration => f.nullable ? '$read?.name' : '$read.name',
    FieldKind.gameObject || FieldKind.behaviour => 'referenceJson($read)',
    _ => read,
  };
}

/// [type]: the enum's or the referenced script's class, prefixed.
String _setter(ExposedField f, String? type) {
  // References arrive resolved (BehaviourField.isReference).
  if (f.kind.isReference) return 'v as ${type ?? 'GameObject'}?';
  final convert = switch (f.kind) {
    FieldKind.number => '_double',
    FieldKind.integer => '_int',
    FieldKind.boolean => '(v) => v as bool',
    FieldKind.string => '(v) => v as String',
    FieldKind.vec3 => '_vec3',
    FieldKind.quat => '_quat',
    FieldKind.assetRef => '_assetRef',
    FieldKind.vec3List => '_vec3List',
    FieldKind.enumeration => '(v) => $type.values.byName(v as String)',
    FieldKind.gameObject || FieldKind.behaviour => throw StateError('unreachable'),
  };
  if (f.nullable) return '_orNull(v, $convert)';
  return switch (f.kind) {
    FieldKind.boolean => 'v as bool',
    FieldKind.string => 'v as String',
    FieldKind.enumeration => '$type.values.byName(v as String)',
    _ => '$convert(v)',
  };
}

String _dartString(String s) =>
    s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll('\$', r'\$').replaceAll('\n', r'\n');

/// A JSON-shaped value as a Dart `const`-able literal.
String _dartLiteral(Object? v) {
  if (v == null) return 'null';
  if (v is String) return "'${_dartString(v)}'";
  if (v is bool || v is int) return '$v';
  if (v is double) {
    if (v.isNaN) return 'double.nan';
    if (v.isInfinite) return v > 0 ? 'double.infinity' : 'double.negativeInfinity';
    return '$v';
  }
  if (v is List) return 'const [${v.map(_dartLiteral).join(', ')}]';
  if (v is Map) {
    return 'const {${v.entries.map((e) => "'${_dartString(e.key as String)}': ${_dartLiteral(e.value)}").join(', ')}}';
  }
  throw ArgumentError.value(v, 'v', 'not a JSON value');
}

// ------------------------------------------------------------------- JSON

/// The JSON Schema 2020-12 for one type's authored `data`. Fields are
/// optional (the class initializer is the default); unknown keys are
/// rejected.
Map<String, Object?> schemaFor(BehaviourClass c) {
  final properties = <String, Object?>{};
  for (final f in c.fields) {
    properties[f.name] = _propertySchema(f);
  }
  return {
    r'$schema': 'https://json-schema.org/draft/2020-12/schema',
    r'$id': schemaIdFor(c.id),
    r'$comment': generatedComment,
    'title': c.id,
    if (c.doc != null) 'description': c.doc,
    'type': 'object',
    'properties': properties,
    'additionalProperties': false,
    'x-fynkel': {
      'kind': 'behaviour',
      'id': c.id,
      'version': c.version,
      'dart': '${c.libraryUri}#${c.className}',
      if (c.icon != null) 'icon': c.icon,
      if (c.category != null) 'category': c.category,
    },
  };
}

Map<String, Object?> _propertySchema(ExposedField f) {
  final s = <String, Object?>{};
  switch (f.kind) {
    case FieldKind.number:
    case FieldKind.integer:
    case FieldKind.boolean:
    case FieldKind.string:
      s['type'] = f.nullable ? [f.kind.typeName, 'null'] : f.kind.typeName;
      if (f.kind == FieldKind.number || f.kind == FieldKind.integer) {
        if (f.min != null) s['minimum'] = f.min;
        if (f.max != null) s['maximum'] = f.max;
      }
    case FieldKind.vec3:
    case FieldKind.quat:
      final n = f.kind == FieldKind.vec3 ? 3 : 4;
      s['type'] = f.nullable ? ['array', 'null'] : 'array';
      s['items'] = {'type': 'number'};
      s['minItems'] = n;
      s['maxItems'] = n;
    case FieldKind.vec3List:
      s['type'] = f.nullable ? ['array', 'null'] : 'array';
      s['items'] = {
        'type': 'array',
        'items': {'type': 'number'},
        'minItems': 3,
        'maxItems': 3,
      };
    case FieldKind.enumeration:
      s['type'] = f.nullable ? ['string', 'null'] : 'string';
      s['enum'] = [...f.enumValues, if (f.nullable) null];
    case FieldKind.gameObject:
    case FieldKind.behaviour:
      final keys = ['entity', if (f.kind == FieldKind.behaviour) 'component'];
      s['type'] = ['object', 'null'];
      s['properties'] = {
        for (final k in keys) k: {'type': 'string'},
      };
      s['required'] = keys;
      s['additionalProperties'] = false;
    case FieldKind.assetRef:
      final ref = {r'$ref': '$envelopeSchemaId#/\$defs/assetRef'};
      if (f.nullable) {
        s['anyOf'] = [
          ref,
          {'type': 'null'}
        ];
      } else {
        s.addAll(ref);
      }
  }
  if (f.hasDefault) s['default'] = f.defaultValue;
  if (f.doc != null) s['description'] = f.doc;
  s['x-fynkel'] = {
    'type': f.kind.typeName,
    if (f.nullable) 'nullable': true,
    ...f.hints,
  };
  return s;
}

/// `lib/generated/behaviours.g.json` for [package]: every type with its
/// Inspector metadata and schema.
String emitJson(String package, List<BehaviourClass> classes) {
  final sorted = _sorted(classes);
  final doc = {
    r'$comment': generatedComment,
    'generator': 'fynkel_generator',
    'package': package,
    'behaviours': [
      for (final c in sorted)
        {
          'id': c.id,
          'version': c.version,
          'class': c.className,
          'library': c.libraryUri,
          if (c.doc != null) 'description': c.doc,
          if (c.icon != null) 'icon': c.icon,
          if (c.category != null) 'category': c.category,
          'fields': [
            for (final f in c.fields)
              {
                'name': f.name,
                'type': f.kind.typeName,
                'nullable': f.nullable,
                if (f.hasDefault) 'default': f.defaultValue,
                ...f.hints,
                if (f.doc != null) 'description': f.doc,
              },
          ],
          'schema': schemaFor(c),
        },
    ],
  };
  return '${const JsonEncoder.withIndent('  ').convert(doc)}\n';
}
