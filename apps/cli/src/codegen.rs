/// Authored records: every authored component and document record plus
/// the records they nest, registry order, once each.
fn authored_records() -> Vec<&'static RecordSchema> {
    fn visit(s: &'static RecordSchema, out: &mut Vec<&'static RecordSchema>) {
        if out.iter().any(|x| x.name == s.name) {
            return;
        }
        for f in s.fields {
            if let FieldType::Nested(n) = f.ty {
                visit(n, out);
            }
        }
        out.push(s);
    }
    let mut out = Vec::new();
    for s in ALL
        .iter()
        .filter(|s| (s.kind == SchemaKind::Component && s.authored) || s.document.is_some())
    {
        visit(s, &mut out);
    }
    out
}

/// Records that are a document kind's top level (`document = "..."`).
fn document_records() -> Vec<&'static RecordSchema> {
    ALL.iter()
        .copied()
        .filter(|s| s.document.is_some())
        .collect()
}

/// `crates/fynkel_document/src/generated.rs`: typed component values ↔ JSON
/// nodes, plus the `ComponentValue` dispatch used by scene instantiation.
fn document_codecs(fp: u64) -> String {
    let mut o = String::new();
    let _ = writeln!(
        o,
        "// GENERATED by `fynkel codegen` from the Rust component schemas (ADR-0012)."
    );
    let _ = writeln!(o, "// Do not edit. Schema fingerprint {fp:#018x}.");
    let _ = writeln!(o);
    let _ = writeln!(o, "use fynkel_core::components::ComponentValue;");
    let _ = writeln!(o);
    let _ = writeln!(o, "use crate::codec::*;");
    let _ = writeln!(o, "use crate::json::Node;");
    let records = authored_records();
    let mut enums: Vec<&'static EnumSchema> = Vec::new();
    for s in &records {
        for f in s.fields {
            if let FieldType::Enum(e) = f.ty {
                if !enums.iter().any(|x| x.name == e.name) {
                    enums.push(e);
                }
            }
        }
    }
    for e in enums {
        let path = format!("::{}", e.rust_path);
        let _ = writeln!(o);
        let _ = writeln!(o, "/// `{}`: lowerCamel variant name.", e.name);
        let _ = writeln!(o, "impl DocumentCodec for {path} {{");
        let _ = writeln!(
            o,
            "    fn from_node(node: &Node) -> Result<Self, FieldError> {{"
        );
        let _ = writeln!(o, "        enum_from_node(node)");
        let _ = writeln!(o, "    }}");
        let _ = writeln!(o, "    fn to_node(&self) -> Node {{");
        let _ = writeln!(o, "        enum_node(self)");
        let _ = writeln!(o, "    }}");
        let _ = writeln!(o, "}}");
    }
    for s in &records {
        let path = format!("::{}", s.rust_path);
        let _ = writeln!(o);
        let _ = writeln!(o, "/// `{}` ({}, id {}).", s.name, s.kind.name(), s.id);
        let _ = writeln!(o, "impl DocumentCodec for {path} {{");
        let _ = writeln!(
            o,
            "    fn from_node(node: &Node) -> Result<Self, FieldError> {{"
        );
        let _ = writeln!(o, "        let m = object(node)?;");
        let _ = writeln!(o, "        let _ = m;");
        // A document record's fields are all optional: an absent one takes
        // the Rust `Default` (the generated schema states the same values).
        let is_document = s.document.is_some();
        if is_document {
            let _ = writeln!(o, "        let d = Self::default();");
        }
        if s.fields.is_empty() {
            let _ = writeln!(o, "        Ok(Self)");
        } else {
            let _ = writeln!(o, "        Ok(Self {{");
            for f in s.fields {
                let name = f.name;
                let reader = match f.ty {
                    FieldType::F32 => "f32_field",
                    FieldType::U32 => "u32_field",
                    FieldType::I32 => "i32_field",
                    FieldType::U64 => "u64_field",
                    FieldType::Bool => "bool_field",
                    FieldType::Vec3 => "vec3_field",
                    FieldType::Vec4 => "vec4_field",
                    FieldType::Quat => "quat_field",
                    FieldType::Str => "str_field",
                    FieldType::AssetRef => "asset_ref_field",
                    FieldType::OptionalAssetRef => "opt_asset_ref_field",
                    FieldType::Enum(_) => "enum_field",
                    FieldType::Nested(_) => "nested_field",
                    FieldType::Entity | FieldType::OptionalEntity => panic!(
                        "{}.{}: authored records cannot hold entity handles",
                        s.name, name
                    ),
                };
                let expr = if is_document {
                    format!("or_default(m, \"{name}\", {reader}, d.{name})?")
                } else {
                    format!("{reader}(m, \"{name}\")?")
                };
                let _ = writeln!(o, "            {name}: {expr},");
            }
            let _ = writeln!(o, "        }})");
        }
        let _ = writeln!(o, "    }}");
        let _ = writeln!(o, "    fn to_node(&self) -> Node {{");
        let _ = writeln!(o, "        object_node(vec![");
        for f in s.fields {
            let name = f.name;
            let v = format!("self.{name}");
            let expr = match f.ty {
                FieldType::F32 => format!("f32_node({v})"),
                FieldType::U32 | FieldType::I32 | FieldType::U64 => {
                    format!("integer_node({v} as i64)")
                }
                FieldType::Bool => format!("bool_node({v})"),
                FieldType::Vec3 => format!("vec3_node({v})"),
                FieldType::Vec4 => format!("vec4_node({v})"),
                FieldType::Quat => format!("quat_node({v})"),
                FieldType::Str => format!("str_node(&{v})"),
                FieldType::AssetRef => format!("asset_ref_node(&{v})"),
                // Unbound optional references are left out of the document.
                FieldType::OptionalAssetRef => format!("opt_asset_ref_node({v}.as_ref())"),
                FieldType::Enum(_) => format!("enum_node(&{v})"),
                FieldType::Nested(_) => format!("{v}.to_node()"),
                FieldType::Entity | FieldType::OptionalEntity => unreachable!(),
            };
            let _ = writeln!(o, "            (\"{name}\", {expr}),");
        }
        let _ = writeln!(o, "        ])");
        let _ = writeln!(o, "    }}");
        let _ = writeln!(o, "}}");
    }
    // Defaults of the document records, for the generated document schemas.
    let _ = writeln!(o);
    let _ = writeln!(
        o,
        "/// `(document kind, Default as a node)` of every document record; the"
    );
    let _ = writeln!(
        o,
        "/// `default` values in `schemas/<kind>.schema.json` come from here."
    );
    let _ = writeln!(
        o,
        "pub fn document_defaults() -> Vec<(&'static str, Node)> {{"
    );
    let _ = writeln!(o, "    vec![");
    for s in document_records() {
        let _ = writeln!(
            o,
            "        (\"{}\", <::{} as Default>::default().to_node()),",
            s.document.unwrap(),
            s.rust_path
        );
    }
    let _ = writeln!(o, "    ]");
    let _ = writeln!(o, "}}");
    // Schemas compiled into fynkel_document (SchemaSet::embedded).
    let _ = writeln!(o);
    let _ = writeln!(
        o,
        "/// `(file name, text)` of every document/component schema."
    );
    let _ = writeln!(o, "pub const EMBEDDED_SCHEMAS: &[(&str, &str)] = &[");
    let _ = writeln!(
        o,
        "    (\"scene.schema.json\", include_str!(\"../../../{SCENE_SCHEMA}\")),"
    );
    let _ = writeln!(
        o,
        "    (\"prefab.schema.json\", include_str!(\"../../../{PREFAB_SCHEMA}\")),"
    );
    for s in document_records() {
        let kind = s.document.unwrap();
        let _ = writeln!(
            o,
            "    (\"{kind}.schema.json\", include_str!(\"../../../schemas/{kind}.schema.json\")),"
        );
    }
    for hand_written in HAND_WRITTEN_SCHEMAS {
        let _ = writeln!(
            o,
            "    (\"{hand_written}\", include_str!(\"../../../schemas/{hand_written}\")),"
        );
    }
    for s in ALL.iter().filter(|s| s.kind == SchemaKind::Component) {
        let _ = writeln!(
            o,
            "    (\"{0}.schema.json\", include_str!(\"../../../schemas/components/{0}.schema.json\")),",
            s.name
        );
    }
    let _ = writeln!(o, "];");
    // ComponentValue dispatch, authored components only.
    let components: Vec<&RecordSchema> = ALL
        .iter()
        .copied()
        .filter(|s| s.kind == SchemaKind::Component && s.authored)
        .collect();
    let _ = writeln!(o);
    let _ = writeln!(o, "/// Authored component type ids, registry order.");
    let _ = writeln!(o, "pub const AUTHORED_COMPONENTS: &[&str] = &[");
    for s in &components {
        let _ = writeln!(o, "    \"{}\",", s.name);
    }
    let _ = writeln!(o, "];");
    let _ = writeln!(o);
    let _ = writeln!(
        o,
        "/// `None` for a type id that is not a built-in authored component."
    );
    let _ = writeln!(
        o,
        "pub fn decode_component(type_id: &str, data: &Node) -> Option<Result<ComponentValue, FieldError>> {{"
    );
    let _ = writeln!(o, "    Some(match type_id {{");
    for s in &components {
        let _ = writeln!(
            o,
            "        \"{}\" => <::{} as DocumentCodec>::from_node(data).map(ComponentValue::{}),",
            s.name,
            s.rust_path,
            rust_ident(s)
        );
    }
    let _ = writeln!(o, "        _ => return None,");
    let _ = writeln!(o, "    }})");
    let _ = writeln!(o, "}}");
    let _ = writeln!(o);
    let _ = writeln!(o, "/// `(type id, data)` of a value.");
    let _ = writeln!(
        o,
        "pub fn encode_component(value: &ComponentValue) -> (&'static str, Node) {{"
    );
    let _ = writeln!(o, "    match value {{");
    for s in &components {
        let _ = writeln!(
            o,
            "        ComponentValue::{}(v) => (\"{}\", v.to_node()),",
            rust_ident(s),
            s.name
        );
    }
    let _ = writeln!(o, "    }}");
    let _ = writeln!(o, "}}");
    o
}
