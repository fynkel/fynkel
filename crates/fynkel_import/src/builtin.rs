//! Built-in assets every cook ships (ADR-0026 §4): the editor's primitive
//! shapes (ADR-0023), so `world.createPrimitive` works in a project that
//! never installed them. A project with its own copy (the editor's
//! `installPrimitives`, same id) cooks that one instead.

use std::path::Path;

use fynkel_contracts::Diagnostic;
use fynkel_document::asset::AssetDatabase;
use fynkel_document::schema::SchemaSet;
use uuid::Uuid;

/// The fixed id of the built-in shapes; every `mesh/<Shape>` and
/// `material/Default` id derives from it (UUID v5).
pub const PRIMITIVES_ID: Uuid = Uuid::from_u128(0xf7a1e5d0_0000_4000_8000_000000000023);

/// Where a project keeps them (the editor installs them there), and so the
/// path the cook's index gives the built-in copy.
pub const PRIMITIVES_PATH: &str = "Fynkel/Primitives.glb";

/// `Primitives.glb` and its sidecar, generated by
/// `crates/fynkel_authoring/assets/primitives.py`.
pub const PRIMITIVES_GLB: &[u8] = include_bytes!("../../fynkel_authoring/assets/Primitives.glb");
pub const PRIMITIVES_META: &str =
    include_str!("../../fynkel_authoring/assets/Primitives.glb.meta.json");

/// `db` with the built-in assets it lacks, their files written under
/// `<cache>/builtin/` (rewritten only when they differ, so the cook's
/// stamps stay warm); `None` when it has them all.
pub fn with_builtins(
    db: &AssetDatabase,
    cache: &Path,
    schemas: &SchemaSet,
    diagnostics: &mut Vec<Diagnostic>,
) -> Option<AssetDatabase> {
    if db.get(PRIMITIVES_ID).is_some() {
        return None;
    }
    let dir = cache.join("builtin");
    let file = dir.join("Primitives.glb");
    let sidecar = dir.join("Primitives.glb.meta.json");
    let write = |path: &Path, bytes: &[u8]| -> std::io::Result<()> {
        if std::fs::read(path).ok().as_deref() != Some(bytes) {
            std::fs::create_dir_all(&dir)?;
            std::fs::write(path, bytes)?;
        }
        Ok(())
    };
    if let Err(e) =
        write(&file, PRIMITIVES_GLB).and_then(|_| write(&sidecar, PRIMITIVES_META.as_bytes()))
    {
        diagnostics.push(Diagnostic::warning(
            fynkel_contracts::Code::IO,
            format!(
                "the built-in primitives could not be written to {}: {e}",
                dir.display()
            ),
        ));
        return None;
    }
    let mut with = db.clone();
    diagnostics.extend(with.add_builtin(&file, PRIMITIVES_PATH, schemas));
    Some(with)
}
