//! Native schema generator (ADR-0012 pipeline (a)):
//! Rust `RecordSchema` registry → JSON Schema, Dart codecs, Rust codecs.
//! Deterministic output; `--check` diffs against the committed files.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use fynkel_contracts::schema::{EnumSchema, FieldType, RecordSchema, SchemaKind};
use fynkel_contracts::ABI_VERSION;
use fynkel_core::schema::{schema_fingerprint, ALL};
use serde_json::{json, Value};

pub enum Outcome {
    Written(usize),
    UpToDate,
    Drift(Vec<PathBuf>),
}

pub const DART_OUT: &str = "packages/fynkel/lib/generated/schema.g.dart";
pub const RUST_OUT: &str = "crates/fynkel_wire/src/generated.rs";
pub const DOCUMENT_OUT: &str = "crates/fynkel_document/src/generated.rs";
pub const JSON_INDEX: &str = "schemas/fynkel.schema.json";
pub const SCENE_SCHEMA: &str = "schemas/scene.schema.json";
pub const PREFAB_SCHEMA: &str = "schemas/prefab.schema.json";
/// Document schemas maintained by hand under `schemas/` (no Rust source of
/// truth) that `fynkel_document` still embeds; the envelope is embedded by
/// `SchemaSet` itself.
pub const HAND_WRITTEN_SCHEMAS: &[&str] = &[
    "shader.schema.json",
    "meta.schema.json",
    "project.schema.json",
    "lock.schema.json",
    "rig.schema.json",
    "blend.schema.json",
    "volume.schema.json",
    "physics_material.schema.json",
];
pub const ENVELOPE_ID: &str = "https://fynkel.dev/schemas/envelope.schema.json";

pub fn run(root: &Path, check: bool) -> Result<Outcome, String> {
    let files = generate();
    if check {
        let mut drift = Vec::new();
        for (rel, content) in &files {
            let path = root.join(rel);
            if std::fs::read_to_string(&path).ok().as_deref() != Some(content.as_str()) {
                drift.push(PathBuf::from(rel));
            }
        }
        return Ok(if drift.is_empty() {
            Outcome::UpToDate
        } else {
            Outcome::Drift(drift)
        });
    }
    for (rel, content) in &files {
        let path = root.join(rel);
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
        }
        std::fs::write(&path, content).map_err(|e| format!("{}: {e}", path.display()))?;
    }
    Ok(Outcome::Written(files.len()))
}

/// All outputs as (repo-relative path, content), deterministic order.
pub fn generate() -> Vec<(String, String)> {
    let fp = schema_fingerprint();
    let mut out = vec![
        (JSON_INDEX.to_string(), json_index(fp)),
        (
            SCENE_SCHEMA.to_string(),
            pretty(&entity_document_schema(EntityDocument::Scene)),
        ),
        (
            PREFAB_SCHEMA.to_string(),
            pretty(&entity_document_schema(EntityDocument::Prefab)),
        ),
        (DART_OUT.to_string(), dart(fp)),
        (RUST_OUT.to_string(), rust(fp)),
        (DOCUMENT_OUT.to_string(), document_codecs(fp)),
    ];
    for s in ALL.iter().filter(|s| s.kind == SchemaKind::Component) {
        out.push((
            format!("schemas/components/{}.schema.json", s.name),
            pretty(&json_schema(s)),
        ));
    }
    for s in document_records() {
        let kind = s.document.unwrap();
        out.push((
            format!("schemas/{kind}.schema.json"),
            pretty(&document_schema(s)),
        ));
    }
    out
}

fn pretty(v: &Value) -> String {
    let mut s = serde_json::to_string_pretty(v).unwrap();
    s.push('\n');
    s
}

fn rust_ident(s: &RecordSchema) -> &str {
    s.rust_path.rsplit("::").next().unwrap()
}

// ------------------------------------------------------------------ JSON

fn json_index(fp: u64) -> String {
    let records: Vec<Value> = ALL
        .iter()
        .map(|s| {
            let offsets = s.offsets();
            json!({
                "kind": s.kind.name(),
                "id": s.id,
                "name": s.name,
                "rust": s.rust_path,
                "doc": s.doc,
                "size": s.wire_size(),
                "fields": s.fields.iter().zip(offsets).map(|(f, off)| {
                    let mut v = json!({
                        "name": f.name,
                        "type": f.ty.name(),
                        "offset": off,
                        "size": f.ty.wire_size(),
                        "doc": f.doc,
                    });
                    if let FieldType::Enum(e) = f.ty {
                        v["variants"] = json!(e.variants);
                    }
                    v
                }).collect::<Vec<_>>(),
            })
        })
        .collect();
    pretty(&json!({
        "$comment": "GENERATED by `fynkel codegen` from the Rust schemas (ADR-0012). Do not edit.",
        "abiVersion": ABI_VERSION,
        "schemaFingerprint": format!("{fp:#018x}"),
        "layout": "little-endian; fields at natural alignment in declaration order; records padded to 8; str = (offset u32, len u32) into the buffer string tail",
        "records": records,
    }))
}

fn json_type(ty: &FieldType) -> Value {
    match ty {
        FieldType::F32 => json!({"type": "number"}),
        FieldType::U32 => json!({"type": "integer", "minimum": 0, "maximum": u32::MAX}),
        FieldType::I32 => json!({"type": "integer", "minimum": i32::MIN, "maximum": i32::MAX}),
        FieldType::U64 | FieldType::Entity => json!({"type": "integer", "minimum": 0}),
        FieldType::OptionalEntity => json!({"type": ["integer", "null"], "minimum": 0}),
        FieldType::Bool => json!({"type": "boolean"}),
        FieldType::Vec3 => {
            json!({"type": "array", "items": {"type": "number"}, "minItems": 3, "maxItems": 3})
        }
        FieldType::Vec4 => {
            json!({"type": "array", "items": {"type": "number"}, "minItems": 4, "maxItems": 4})
        }
        FieldType::Quat => {
            json!({"type": "array", "items": {"type": "number"}, "minItems": 4, "maxItems": 4, "description": "[x, y, z, w]"})
        }
        FieldType::Str => json!({"type": "string"}),
        FieldType::Nested(s) => json!({"$ref": format!("{}.schema.json", s.name)}),
        FieldType::AssetRef => json!({"$ref": format!("{ENVELOPE_ID}#/$defs/assetRef")}),
        FieldType::OptionalAssetRef => {
            json!({"oneOf": [{"$ref": format!("{ENVELOPE_ID}#/$defs/assetRef")}, {"type": "null"}]})
        }
        FieldType::Enum(e) => {
            json!({"type": "string", "enum": e.variants, "x-fynkel": {"enum": e.name}})
        }
    }
}

fn json_schema(s: &RecordSchema) -> Value {
    let mut props = serde_json::Map::new();
    let mut required = Vec::new();
    for f in s.fields {
        let mut t = json_type(&f.ty);
        if !f.doc.is_empty() {
            t["description"] = Value::String(f.doc.to_string());
        }
        props.insert(f.name.to_string(), t);
        if !matches!(
            f.ty,
            FieldType::OptionalEntity | FieldType::OptionalAssetRef
        ) {
            required.push(f.name);
        }
    }
    json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": format!("https://fynkel.dev/schemas/components/{}.schema.json", s.name),
        "$comment": "GENERATED by `fynkel codegen`. Do not edit.",
        "title": s.name,
        "description": s.doc,
        "type": "object",
        "properties": props,
        "required": required,
        "additionalProperties": false,
        "x-fynkel": {"kind": s.kind.name(), "id": s.id, "rust": s.rust_path, "wireSize": s.wire_size(), "authored": s.authored},
    })
}

/// The `properties` of a document record: every field optional, with the
/// Rust `Default` as the schema `default` (read through the generated
/// document codec, so the two cannot drift).
fn document_properties(s: &RecordSchema) -> serde_json::Map<String, Value> {
    let kind = s.document.expect("a document record");
    let defaults = fynkel_document::generated::document_defaults()
        .into_iter()
        .find(|(k, _)| *k == kind)
        .map(|(_, node)| node.to_serde())
        .unwrap_or_else(|| {
            panic!("no document defaults for {kind} (regenerate after adding the record)")
        });
    let mut props = serde_json::Map::new();
    for f in s.fields {
        let mut t = json_type(&f.ty);
        if !f.doc.is_empty() {
            t["description"] = Value::String(f.doc.to_string());
        }
        match &defaults[f.name] {
            Value::Null => {}
            v => t["default"] = v.clone(),
        }
        props.insert(f.name.to_string(), t);
    }
    props
}

/// `schemas/<kind>.schema.json` for a document record.
fn document_schema(s: &RecordSchema) -> Value {
    match s.document {
        Some("material") => material_schema(s),
        Some("settings") => settings_schema(s),
        other => panic!("no document schema template for {other:?}"),
    }
}

/// `settings.schema.json` (blueprint §19.2d item 12): the user's
/// `settings.json` — not an asset, so no envelope (no id, no name; the
/// kind and format version only, like an input recording) — with the
/// `fynkel.Settings` fields flat on the document and the `input.rebinds`
/// map an action's bindings replace the project's with. Every field is
/// optional and defaults as stated; ranges and the binding grammar are
/// semantic rules (`fynkel_document::settings::validate`, FYN-U0002).
fn settings_schema(s: &RecordSchema) -> Value {
    let mut properties = serde_json::Map::new();
    properties.insert(
        "fynkel".into(),
        json!({"const": "settings", "description": "The document kind."}),
    );
    properties.insert(
        "formatVersion".into(),
        json!({"const": 1, "description": "The settings format; `fynkel migrate` does not touch settings files, a game reads an older one with defaults for what it lacks."}),
    );
    properties.extend(document_properties(s));
    properties.insert(
        "input".into(),
        json!({
            "type": "object",
            "description": "Input rebinds: an action's bindings here replace the project file's for this user; an action absent here keeps the project's.",
            "properties": {
                "rebinds": {
                    "type": "object",
                    "propertyNames": {"type": "string", "minLength": 1},
                    "additionalProperties": {
                        "type": "array",
                        "items": {"type": "string", "pattern": "^(keyboard|mouse|gamepad|touch):[A-Za-z0-9_./+-]{1,64}(\\*[0-9]*\\.?[0-9]+([eE][-+]?[0-9]+)?)?$"},
                    },
                    "default": {},
                },
            },
            "additionalProperties": false,
            "default": {"rebinds": {}},
        }),
    );
    json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://fynkel.dev/schemas/settings.schema.json",
        "$comment": "GENERATED by `fynkel codegen` from `fynkel_core::settings::Settings` (ADR-0012). Do not edit.",
        "title": "Fynkel user settings",
        "description": "One `settings.json` per user under the platform's application-support directory (blueprint §19.2d item 12): audio bus gains, the quality profile and input rebinds. The Rust `fynkel.Settings` record's fields plus `input.rebinds`; a game reads it at startup through the Dart `Settings` service and writes it on change.",
        "type": "object",
        "properties": properties,
        "required": ["fynkel", "formatVersion"],
        "patternProperties": {"^x-": true},
        "additionalProperties": false,
        "x-fynkel": {"kind": "record", "name": s.name, "rust": s.rust_path, "wireSize": s.wire_size(), "document": "settings"},
    })
}

/// `material.schema.json` (blueprint §6 Materials, §19.2d item 2): the
/// envelope, `shader`, the `fynkel.PbrMaterial` fields (what a
/// `fynkel.pbr@1` material sets) and a custom shader's manifest-typed
/// `parameters`/`textures`. Which group a document may use follows from
/// its shader and is a semantic rule (`fynkel material validate`, FYN-D0307)
/// rather than a conditional here: a failed `if`/`then` branch would turn
/// every field of the branch into "unexpected property".
fn material_schema(s: &RecordSchema) -> Value {
    let shader_schema = "https://fynkel.dev/schemas/shader.schema.json";
    let mut properties = serde_json::Map::new();
    properties.insert(
        "shader".into(),
        json!({
            "$ref": format!("{shader_schema}#/$defs/shaderId"),
            "description": "The shader this material sets values for: `fynkel.pbr@1` (built in, the fields below) or a custom manifest's id (`parameters` and `textures`).",
        }),
    );
    properties.extend(document_properties(s));
    properties.insert(
        "parameters".into(),
        json!({
            "type": "object",
            "description": "Custom shaders only: parameter values; anything not set takes the manifest default.",
            "propertyNames": {"$ref": format!("{shader_schema}#/$defs/identifier")},
            "additionalProperties": {
                "oneOf": [
                    {"type": "number"},
                    {"type": "boolean"},
                    {"type": "array", "items": {"type": "number"}, "minItems": 2, "maxItems": 4},
                ],
            },
        }),
    );
    properties.insert(
        "textures".into(),
        json!({
            "type": "object",
            "description": "Custom shaders only: texture slot → binding.",
            "propertyNames": {"$ref": format!("{shader_schema}#/$defs/identifier")},
            "additionalProperties": {"$ref": "#/$defs/textureBinding"},
        }),
    );
    json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://fynkel.dev/schemas/material.schema.json",
        "$comment": "GENERATED by `fynkel codegen` from `fynkel_core::material::PbrMaterial` (ADR-0012). Do not edit.",
        "title": "Fynkel material document",
        "description": "A shader id plus the values a material sets (blueprint §6 Materials and shaders). For the built-in `fynkel.pbr@1` the fields are those of the Rust `fynkel.PbrMaterial` record (factors, five texture slots, alpha mode, double-sidedness); every one is optional and defaults as stated. A custom shader instead takes typed `parameters` and `textures` checked against its manifest. Which group applies, ranges and slot existence are semantic rules (`fynkel material validate`). Shadow flags live on `fynkel.MeshRenderer`.",
        "type": "object",
        "allOf": [{"$ref": ENVELOPE_ID}],
        "properties": properties,
        "required": ["shader"],
        "patternProperties": {"^x-": true},
        "unevaluatedProperties": false,
        "x-fynkel": {"kind": "record", "name": s.name, "rust": s.rust_path, "wireSize": s.wire_size(), "document": "material"},
        "$defs": {
            "textureBinding": {
                "type": "object",
                "properties": {
                    "texture": {"$ref": format!("{ENVELOPE_ID}#/$defs/assetRef")},
                    "colorSpace": {"enum": ["srgb", "linear"], "description": "Overrides the slot's colour space."},
                    "uvSet": {"type": "integer", "minimum": 0, "maximum": 1, "default": 0},
                    "sampler": {"$ref": "#/$defs/sampler"},
                },
                "required": ["texture"],
                "additionalProperties": false,
            },
            "sampler": {
                "type": "object",
                "properties": {
                    "filter": {"enum": ["linear", "nearest"], "default": "linear"},
                    "mipmaps": {"type": "boolean", "default": true},
                    "wrap": {"enum": ["repeat", "clamp", "mirror"], "default": "repeat"},
                    "anisotropy": {"type": "integer", "minimum": 1, "maximum": 16, "default": 1},
                },
                "additionalProperties": false,
            },
        },
    })
}

fn component_schema_id(name: &str) -> String {
    format!("https://fynkel.dev/schemas/components/{name}.schema.json")
}

/// `scene.schema.json` (blueprint §6, §19.2c item 3): the document model
/// plus, for every authored built-in component, a conditional that binds
/// `data` to that component's schema. Unknown component types validate
/// structurally (`data` is any object) and are reported by the semantic
/// pass, so a project with a missing plugin still opens.
#[derive(Clone, Copy, PartialEq, Eq)]
enum EntityDocument {
    Scene,
    Prefab,
}

/// `scene.schema.json` and `prefab.schema.json` share the entity/component
/// model; an entity of either may be a prefab instance (`prefab`), and a
/// prefab declares its one `root` (ADR-0022).
fn entity_document_schema(kind: EntityDocument) -> Value {
    let uuid = json!({"$ref": format!("{ENVELOPE_ID}#/$defs/uuid")});
    let asset_ref = json!({"$ref": format!("{ENVELOPE_ID}#/$defs/assetRef")});
    let type_id = json!({"$ref": format!("{ENVELOPE_ID}#/$defs/typeId")});
    let bindings: Vec<Value> = ALL
        .iter()
        .filter(|s| s.kind == SchemaKind::Component && s.authored)
        .map(|s| {
            json!({
                "if": {"properties": {"type": {"const": s.name}}},
                "then": {"properties": {"data": {"$ref": component_schema_id(s.name)}}},
            })
        })
        .collect();
    let mut entity_properties = json!({
        "name": {"type": "string", "maxLength": 256},
        "active": {
            "type": "boolean",
            "description": "The entity's own active flag (absent = true). An entity is active in the hierarchy when it and every ancestor are; an inactive subtree is not drawn, simulated or updated.",
        },
        "parent": {"oneOf": [uuid, {"type": "null"}]},
        "children": {
            "type": "array",
            "description": "Ordered child ids; every listed child must name this entity as its parent.",
            "items": uuid,
        },
        "components": {
            "type": "object",
            "propertyNames": uuid,
            "additionalProperties": {"$ref": "#/$defs/component"},
        },
        "editorNotes": {"type": "string"},
    });
    let mut properties = json!({
        "entities": {
            "type": "object",
            "description": "Entity records keyed by their persistent id. Roots are the entities with a null parent, in key order.",
            "propertyNames": uuid,
            "additionalProperties": {"$ref": "#/$defs/entity"},
        },
    });
    let mut defs = json!({
        "component": {
            "type": "object",
            "properties": {
                "type": type_id,
                "version": {"type": "integer", "minimum": 1},
                "data": {"type": "object"},
                "editorNotes": {"type": "string"},
            },
            "required": ["type", "version", "data"],
            "patternProperties": {"^x-": true},
            "additionalProperties": false,
            "allOf": bindings,
        },
    });
    // Both documents may hold prefab instances: a scene's are expanded at
    // load/cook, a prefab's when the library is flattened (nested prefabs,
    // M3-08b; a cycle is `FYN-D0402`).
    entity_properties["prefab"] = json!({"$ref": "#/$defs/prefabInstance"});
    defs["prefabInstance"] = json!({
        "type": "object",
        "description": "Makes this entity a prefab instance: it is the prefab's root (ADR-0022) — it keeps its id, name and active flag, takes the root's components (it has none of its own) and the root's children before its own — and the prefab's other ids are remapped per instance. Overrides apply in order.",
        "properties": {
            "asset": asset_ref,
            "instance": {"allOf": [uuid], "description": "Stable per instance; prefab-local ids are derived from it."},
            "overrides": {"type": "array", "items": {"$ref": "#/$defs/override"}},
        },
        "required": ["asset", "instance"],
        "patternProperties": {"^x-": true},
        "additionalProperties": false,
    });
    defs["override"] = json!({
        "type": "object",
        "description": "One explicit operation on the instance, addressed by prefab-local ids (or ids introduced by an earlier addObject/addComponent). `setField` with a null value sets null; `unsetField` removes the field; `setActive` sets the entity's own active flag.",
        "properties": {
            "op": {"enum": ["setField", "unsetField", "addComponent", "removeComponent", "addObject", "removeObject", "setActive"]},
            "entity": uuid,
            "component": uuid,
            "field": {"type": "string", "minLength": 1},
            "value": {"description": "setField: the new value; setActive: a boolean."},
            "type": type_id,
            "version": {"type": "integer", "minimum": 1},
            "data": {"type": "object"},
            "name": {"type": "string", "maxLength": 256},
            "parent": {"allOf": [uuid], "description": "addObject: the prefab-local parent (the root at the top)."},
            "components": {
                "type": "object",
                "propertyNames": uuid,
                "additionalProperties": {"$ref": "#/$defs/component"},
            },
        },
        "required": ["op", "entity"],
        "allOf": [
            {"if": {"properties": {"op": {"const": "setField"}}}, "then": {"required": ["component", "field", "value"]}},
            {"if": {"properties": {"op": {"const": "unsetField"}}}, "then": {"required": ["component", "field"]}},
            {"if": {"properties": {"op": {"const": "addComponent"}}}, "then": {"required": ["component", "type", "version", "data"]}},
            {"if": {"properties": {"op": {"const": "removeComponent"}}}, "then": {"required": ["component"]}},
            {"if": {"properties": {"op": {"const": "addObject"}}}, "then": {"required": ["name", "parent"]}},
            {"if": {"properties": {"op": {"const": "setActive"}}}, "then": {"required": ["value"], "properties": {"value": {"type": "boolean"}}}},
        ],
        "patternProperties": {"^x-": true},
        "additionalProperties": false,
    });
    let (id, title, description, required) = match kind {
        EntityDocument::Scene => {
            (
                "scene",
                "Fynkel scene document",
                "UUID-keyed entities and component instances; child order is stored per entity (blueprint §6). An entity with `prefab` is a prefab instance. Semantic rules (dangling references, cycles, duplicate component types, prefab resolution and override targets) are checked by `fynkel scene validate`, not by this schema.",
                json!(["entities"]),
            )
        }
        EntityDocument::Prefab => {
            properties["root"] = json!({
                "allOf": [uuid],
                "description": "The prefab's one root: its only parentless entity; every other entity descends from it (ADR-0022). An instance of the prefab is this entity.",
            });
            (
                "prefab",
                "Fynkel prefab document",
                "The scene entity model plus its one `root` (blueprint §6 Prefabs, ADR-0022). An entity with `prefab` is a nested prefab instance, expanded when the prefab is (a cycle is `FYN-D0402`). `fynkel prefab validate` checks the semantic rules.",
                json!(["entities", "root"]),
            )
        }
    };
    defs["entity"] = json!({
        "type": "object",
        "properties": entity_properties,
        "required": ["name", "parent", "children", "components"],
        "patternProperties": {"^x-": true},
        "additionalProperties": false,
    });
    json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": format!("https://fynkel.dev/schemas/{id}.schema.json"),
        "$comment": "GENERATED by `fynkel codegen` from the document model and the Rust component schemas (ADR-0012). Do not edit.",
        "title": title,
        "description": description,
        "type": "object",
        "allOf": [{"$ref": ENVELOPE_ID}],
        "properties": properties,
        "required": required,
        "patternProperties": {"^x-": true},
        "unevaluatedProperties": false,
        "$defs": defs,
    })
}

// ------------------------------------------------------------------ Dart

fn camel(s: &str) -> String {
    let mut out = String::new();
    let mut up = false;
    for c in s.chars() {
        if c == '_' {
            up = true;
        } else if up {
            out.push(c.to_ascii_uppercase());
            up = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn dart_type(ty: &FieldType) -> String {
    match ty {
        FieldType::F32 => "double".into(),
        FieldType::U32 | FieldType::I32 | FieldType::U64 | FieldType::Entity => "int".into(),
        FieldType::OptionalEntity => "int?".into(),
        FieldType::Bool => "bool".into(),
        FieldType::Vec3 => "Vec3".into(),
        FieldType::Vec4 => "Vec4".into(),
        FieldType::Quat => "Quat".into(),
        FieldType::Str => "String".into(),
        FieldType::Nested(s) => rust_ident(s).into(),
        FieldType::AssetRef => "AssetRef".into(),
        FieldType::OptionalAssetRef => "AssetRef?".into(),
        FieldType::Enum(e) => enum_ident(e).into(),
    }
}

/// A Dart constant expression for [v], a field's value in its document
/// form (`fynkel_document`'s codec: the schema's field names, enums by
/// lowerCamel name, asset references as `{ asset, sub? }`), or `None`
/// when the value does not fit the field's type.
fn dart_const(ty: &FieldType, v: &Value) -> Option<String> {
    fn float(v: &Value) -> Option<String> {
        // Through f32 so the text is the shortest that round-trips on the
        // wire (`0.05`, not `0.05000000074505806`).
        let x = v.as_f64()? as f32;
        if !x.is_finite() {
            return None;
        }
        let t = format!("{x}");
        Some(if t.contains(['.', 'e', 'E']) {
            t
        } else {
            format!("{t}.0")
        })
    }
    fn floats(v: &Value, n: usize) -> Option<String> {
        let a = v.as_array().filter(|a| a.len() == n)?;
        let parts: Option<Vec<String>> = a.iter().map(float).collect();
        Some(parts?.join(", "))
    }
    fn string(s: &str) -> String {
        let mut o = String::from("'");
        for c in s.chars() {
            match c {
                '\\' => o.push_str("\\\\"),
                '\'' => o.push_str("\\'"),
                '$' => o.push_str("\\$"),
                '\n' => o.push_str("\\n"),
                c => o.push(c),
            }
        }
        o.push('\'');
        o
    }
    Some(match ty {
        FieldType::F32 => float(v)?,
        FieldType::U32 | FieldType::U64 => v.as_u64()?.to_string(),
        FieldType::I32 => v.as_i64()?.to_string(),
        FieldType::Bool => v.as_bool()?.to_string(),
        FieldType::Vec3 => format!("Vec3({})", floats(v, 3)?),
        FieldType::Vec4 => format!("Vec4({})", floats(v, 4)?),
        FieldType::Quat => format!("Quat({})", floats(v, 4)?),
        FieldType::Str => string(v.as_str()?),
        FieldType::AssetRef => {
            let asset = v.get("asset")?.as_str()?;
            let sub = v
                .get("sub")
                .and_then(Value::as_str)
                .filter(|s| !s.is_empty());
            match sub {
                None if asset == "00000000-0000-0000-0000-000000000000" => "AssetRef.none".into(),
                None => format!("AssetRef({})", string(asset)),
                Some(sub) => format!("AssetRef({}, sub: {})", string(asset), string(sub)),
            }
        }
        FieldType::Enum(e) => {
            let name = v.as_str()?;
            e.variants.iter().find(|x| **x == name)?;
            format!("{}.{name}", enum_ident(e))
        }
        FieldType::Nested(s) => {
            let mut args = Vec::new();
            for f in s.fields {
                args.push(format!(
                    "{}: {}",
                    camel(f.name),
                    dart_const(&f.ty, v.get(f.name)?)?
                ));
            }
            format!("{}({})", rust_ident(s), args.join(", "))
        }
        FieldType::Entity | FieldType::OptionalEntity | FieldType::OptionalAssetRef => return None,
    })
}

fn enum_ident(e: &EnumSchema) -> &str {
    e.rust_path.rsplit("::").next().unwrap()
}

/// Every enum used by a field in `ALL`, first-use order, once each.
fn enums() -> Vec<&'static EnumSchema> {
    let mut out: Vec<&'static EnumSchema> = Vec::new();
    for s in ALL {
        for f in s.fields {
            if let FieldType::Enum(e) = f.ty {
                if !out.iter().any(|x| x.name == e.name) {
                    out.push(e);
                }
            }
        }
    }
    out
}

