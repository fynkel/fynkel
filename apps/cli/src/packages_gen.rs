//! `lib/generated/packages.g.dart` (ADR-0029 §2): `registerPackages`, which
//! registers the behaviours and data types of every Fynkel package the game
//! depends on and then the game's own, in the package graph's order. The
//! game calls it once (`lib/game/game.dart`), and the editor host does too,
//! so a new package needs no setup call. Written by `fynkel codegen
//! --project <dir>` beside the behaviour bindings.

use std::path::Path;

use fynkel_document::packages::package_types;

pub const DART_OUT: &str = "lib/generated/packages.g.dart";

/// The Dart source for the project at `project`, or `None` when the Dart
/// package is not a project's (no `fynkel.project.json`: a package
/// generates only its own bindings).
pub fn generate(project: &Path) -> Option<String> {
    if !project.join("fynkel.project.json").is_file() {
        return None;
    }
    let packages: Vec<String> = package_types(project)
        .packages
        .into_iter()
        .filter(|p| p.root.join(crate::behaviours::DART_OUT).is_file())
        .map(|p| p.name)
        .collect();
    let game = project.join(crate::behaviours::DART_OUT).is_file();
    Some(render(&packages, game))
}

fn render(packages: &[String], game: bool) -> String {
    let under_lib = crate::behaviours::DART_OUT.trim_start_matches("lib/");
    let mut imports = String::new();
    let mut calls = String::new();
    for name in packages {
        imports.push_str(&format!(
            "import 'package:{name}/{under_lib}' as _{name};\n"
        ));
        calls.push_str(&format!(
            "  _{name}.registerBehaviours(registry, replace: replace);\n"
        ));
    }
    if game {
        imports.push_str("import 'behaviours.g.dart' as _game;\n");
        calls.push_str("  _game.registerBehaviours(registry, replace: replace);\n");
    }
    let which = if packages.is_empty() {
        "the game's".to_string()
    } else {
        format!(
            "{}, then the game's",
            packages
                .iter()
                .map(|p| format!("`{p}`'s"))
                .collect::<Vec<_>>()
                .join(", ")
        )
    };
    format!(
        "// GENERATED by `fynkel codegen` (ADR-0029). Do not edit.\n\
         // Every package's behaviours and data types, dependencies first, the game last.\n\
         //\n\
         // ignore_for_file: type=lint\n\
         \n\
         import 'package:fynkel/gameplay.dart' show BehaviourRegistry;\n\
         {imports}\
         \n\
         /// Registers {which} behaviours and data types.\n\
         void registerPackages(BehaviourRegistry registry, {{bool replace = false}}) {{\n\
         {calls}\
         }}\n"
    )
}

#[cfg(test)]
mod tests {
    use super::render;

    #[test]
    fn packages_register_before_the_game() {
        let text = render(&["pickups".into(), "props".into()], true);
        assert!(text.contains(
            "import 'package:pickups/generated/behaviours.g.dart' as _pickups;\n\
             import 'package:props/generated/behaviours.g.dart' as _props;\n\
             import 'behaviours.g.dart' as _game;\n"
        ));
        assert!(text.contains(
            "  _pickups.registerBehaviours(registry, replace: replace);\n  \
             _props.registerBehaviours(registry, replace: replace);\n  \
             _game.registerBehaviours(registry, replace: replace);\n}\n"
        ));
        assert!(text.contains("/// Registers `pickups`'s, `props`'s, then the game's behaviours"));
        let alone = render(&[], true);
        assert!(alone.contains("/// Registers the game's behaviours and data types."));
        assert!(!alone.contains("package:pickups"));
    }
}
